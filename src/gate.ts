/** `git add` runs filter commands from git config. Filters the user set up
 *  globally (git-lfs, etc.) are theirs; filters defined in *this repo's*
 *  .git/config could come from someone else (a repo shared as an archive).
 *  Refuse those unless the user says they trust them. */
function ensureRepoConfigIsInert(root: string): void {
  if (process.env.OWNERSHIP_GATE_TRUST_REPO_CONFIG === "1") return;
  const out = git(root, ["config", "--show-scope", "--get-regexp", "^filter\\..*\\.(clean|smudge|process)$"], { check: false });
  const local = new Set<string>();
  for (const line of splitLines(out)) {
    const parts = line.trim().split(/\s+/);
    if ((parts[0] === "local" || parts[0] === "worktree") && parts.length > 1) local.add(parts[1]);
  }
  if (local.size) {
    throw new GateError(
      `This repo's own .git/config defines filter commands (${sorted(local).join(", ")}) that git would run while the gate reads your changes. ` +
        "If you set these up yourself (e.g. git-crypt, or git-lfs installed with --local), rerun with OWNERSHIP_GATE_TRUST_REPO_CONFIG=1.",
    );
  }
}

/** A throwaway copy of the index with everything `git add -A` would stage.
 *  Its blob ids are exactly what a commit would contain — clean filters,
 *  line-ending rules, file↔directory swaps and submodules included — and the
 *  user's real index is never touched. */
function withWorktreeIndex<T>(root: string, fn: (env: Record<string, string>) => T): T {
  let real = git(root, ["rev-parse", "--git-path", "index"]).trim();
  if (!isAbsolute(real)) real = join(root, real);
  const dir = mkdtempSync(join(tmpdir(), "ownership-gate-index-"));
  const tmp = join(dir, "index");
  try {
    if (exists(real)) {
      copyFileSync(real, tmp);
      // Keep the copy's mtime at (or just below) the real index's. Git's
      // "racy clean" check re-reads files modified at or after the index's
      // mtime; a fresh mtime would make git trust stale stat data and miss a
      // same-size edit made in the same second as the last index write.
      const st = statSync(real, { bigint: true });
      const t = Number(st.mtimeNs / 1_000_000n) / 1000 - 0.001;
      utimesSync(tmp, t, t);
    }
    const env = { GIT_INDEX_FILE: tmp };
    ensureRepoConfigIsInert(root);
    gitBytes(root, [...WORKTREE_SAFE, "add", "-A"], { env });
    return fn(env);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const UTF8 = new TextDecoder("utf-8", { fatal: true });
function decodePath(raw: Buffer): string {
  try {
    return UTF8.decode(raw);
  } catch {
    throw new GateError(`File name ${JSON.stringify(raw.toString("latin1"))} is not valid UTF-8; the gate can't track it reliably. Rename it.`);
  }
}

function splitNul(buf: Buffer): Buffer[] {
  const out: Buffer[] = [];
  let start = 0;
  for (let i = 0; i < buf.length; i++) {
    if (buf[i] === 0) {
      out.push(buf.subarray(start, i));
      start = i + 1;
    }
  }
  out.push(buf.subarray(start));
  return out;
}

/** [{path: {mode, blob, base, base_mode}}, untracked paths, fork point] for
 *  every file the change touches against the fork point, gate plumbing
 *  excluded. rev=null means the working tree, as `git add -A` would commit it.
 *  Only `git diff --raw` is used: its output doesn't depend on diff.* config,
 *  attributes, or GIT_DIFF_OPTS. */
export function collectChanges(root: string, base: string, rev?: string | null): [Changes, Set<string>, string] {
  const target = rev || "HEAD";
  if (!refExists(root, target)) throw new GateError("This branch has no commits yet — commit something first.");
  const mb = git(root, ["merge-base", base, target], { check: false }).trim();
  if (!mb) throw new GateError(`No common history between ${base} and ${target}. In CI, check out with fetch-depth: 0.`);
  const rawArgs = ["diff", "--raw", "-z", "--no-abbrev", "--no-renames", "--ignore-submodules=none"];
  let raw: Buffer;
  let untracked = new Set<string>();
  if (rev) raw = gitBytes(root, [...rawArgs, mb, rev]);
  else {
    raw = withWorktreeIndex(root, (env) => gitBytes(root, [...rawArgs, "--cached", mb], { env }));
    const out = gitBytes(root, [...WORKTREE_SAFE, "ls-files", "--others", "--exclude-standard", "-z"]);
    untracked = new Set(splitNul(out).filter((p) => p.length).map(decodePath));
  }
  const fields = splitNul(raw);
  const changes: Changes = dict();
  let i = 0;
  while (i < fields.length - 1) {
    const meta = fields[i].toString("latin1");
    if (!meta.startsWith(":")) {
      i++;
      continue;
    }
    const [oldmode, newmode, oldsha, newsha] = meta.slice(1).split(/\s+/);
    const path = decodePath(fields[i + 1]);
    i += 2;
    if (!isPlumbing(path, newmode)) changes[path] = { mode: newmode, blob: newsha, base: oldsha, base_mode: oldmode };
  }
  return [Object.fromEntries(sorted(Object.keys(changes)).map((k) => [k, changes[k]])), untracked, mb];
}

function merge3(ours: Buffer, base: Buffer, theirs: Buffer): Buffer | null {
  const dir = mkdtempSync(join(tmpdir(), "ownership-gate-merge-"));
  try {
    const paths = ([["ours", ours], ["base", base], ["theirs", theirs]] as const).map(([name, data]) => {
      const p = join(dir, name);
      writeFileSync(p, data);
      return p;
    });
    const r = run("git", ["merge-file", "-p", "-q", ...paths], { cwd: dir, env: gitEnv() });
    return r.status === 0 ? r.stdout : null;
  } catch {
    return null;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const isChange = (v: unknown): v is Change =>
  isObj(v) && ["mode", "blob", "base", "base_mode"].every((k) => typeof v[k] === "string");

/** 'exact' if `current` is the verified change; 'merged' if it is the verified
 *  change carried onto a newer base; null otherwise. For 'merged', the only
 *  accepted difference is the base's own edits: we replay them onto the
 *  verified content with a 3-way merge and require the result to equal the
 *  current content byte for byte. The file mode is merged the same way.
 *  Anything else (a conflict, a binary file, a missing object) is a change. */
function matchKind(root: string, verified: unknown, current: Change): "exact" | "merged" | null {
  if (!isChange(verified)) return null;
  if (verified.mode === current.mode && verified.blob === current.blob && verified.base === current.base && verified.base_mode === current.base_mode) return "exact";
  const expectedMode = verified.mode === verified.base_mode ? current.base_mode : verified.mode;
  if (current.mode !== expectedMode) return null;
  // Base content unchanged: only a base mode change can explain a difference.
  if (verified.base === current.base) return current.blob === verified.blob ? "merged" : null;
  if (!REGULAR_MODES.includes(current.mode) || !REGULAR_MODES.includes(verified.mode)) return null;
  if ([verified.blob, verified.base, current.base, current.blob].includes(ZERO_SHA)) return null;
  const blobs = [verified.blob, verified.base, current.base, current.blob].map((s) => readBlob(root, s));
  if (blobs.some((b) => b === null)) return null;
  const [vBlob, vBase, cBase, cBlob] = blobs as Buffer[];
  if (blobs.some((b) => (b as Buffer).subarray(0, 8000).includes(0))) return null; // binary: must be re-verified
  const merged = merge3(vBlob, vBase, cBase);
  return merged !== null && merged.equals(cBlob) ? "merged" : null;
}

// ---------------------------------------------------------------- the report

export function renderReport(data: Report & { branch: string; date: string; base: string; version: number }): string {
  const lines = [
    `# Ownership check — ${data.branch}`,
    `Date: ${data.date} · Base: ${data.base} · Gate v${data.version}`,
    "",
    "## Summary (in the developer's own words)",
    data.summary.trim(),
    "",
    "## Verified understanding",
  ];
  for (const path of sorted(Object.keys(data.verified))) lines.push(`- \`${path}\` — ` + (get(data.verified, path) ?? []).join("; "));
  const unverified = sorted(Object.keys(data.files).filter((p) => !own(data.verified, p)));
  if (unverified.length) lines.push("", "Also in this change (reviewed, no specific questions): " + unverified.map((p) => `\`${p}\``).join(", "));
  lines.push("", DATA_MARKER, "```json", stableJson(data, 1), "```", "");
  return lines.join("\n");
}

function extractData(text: string): string | null {
  const after = text.split(DATA_MARKER).slice(1).join(DATA_MARKER);
  const m = /```json\n([\s\S]*?)\n```/.exec(after);
  return m ? m[1] : null;
}

export function parseReport(text: string): Report {
  if (!text.includes(DATA_MARKER)) throw new GateError("Report is missing its data block — run the check again to regenerate it.");
  const block = extractData(text);
  if (block === null) throw new GateError("Report data block is malformed — run the check again to regenerate it.");
  let data: unknown;
  try {
    data = JSON.parse(block);
  } catch (e) {
    throw new GateError(`Report data is not valid JSON (${(e as Error).message}) — run the check again.`);
  }
  if (!(isObj(data) && isObj(data.files) && isObj(data.verified) && typeof data.summary === "string")) {
    throw new GateError("Report data has the wrong shape — run the check again to regenerate it.");
  }
  for (const v of Object.values(data.verified as Record<string, unknown>)) {
    if (!Array.isArray(v) || !v.every((x) => typeof x === "string")) throw new GateError("Report data has the wrong shape — run the check again to regenerate it.");
  }
  if (data.version !== GATE_VERSION) {
    throw new GateError(`Report was made by gate v${String(data.version)}; this gate is v${GATE_VERSION}. If your branch is behind the base, merge it first; then run the check again.`);
  }
  return data as unknown as Report;
}

export function readReport(root: string, branch: string, rev?: string | null): Report | null {
  const rel = reportRelpath(branch);
  if (rev) {
    if (!hasFile(root, rev, rel)) return null;
    return parseReport(showSmall(root, rev, rel, MAX_REPORT_BYTES));
  }
  const path = join(root, rel);
  return lstat(path) ? parseReport(readSmall(path, MAX_REPORT_BYTES)) : null;
}

const unusable = (e: unknown): [Report, string] => [
  { files: {}, verified: {}, summary: "", _outdated: true },
  `Existing report can't be used (${(e as Error).message}); its files need verifying again.`,
];

/** Parse a report for status/save. An outdated or broken one isn't a dead end
 *  — but it isn't a clean slate either: its files are treated as needing
 *  re-verification, so deleting or corrupting a report can't reset the rules. */
function parseLenient(text: string): [Report, string | null] {
  try {
    return [parseReport(text), null];
  } catch (e) {
    let files: Record<string, unknown> = {};
    if (text.includes(DATA_MARKER)) {
      try {
        const data = JSON.parse(extractData(text) ?? "null");
        if (isObj(data) && isObj(data.files)) files = data.files;
      } catch {
        /* keep empty */
      }
    }
    // Old-format entries never match, so every file in it reads as changed.
    return [{ files, verified: {}, summary: "", _outdated: true }, `Existing report can't be used (${(e as Error).message}); its files need verifying again.`];
  }
}

/** The report to compare against: the working-tree one, or if it's gone, the
 *  last one committed on this branch (so deleting it doesn't help). */
function previousReport(root: string, branch: string, baseRef: string): [Report | null, string | null] {
  const rel = reportRelpath(branch);
  const path = join(root, rel);
  if (lstat(path)) {
    try {
      return parseLenient(readSmall(path, MAX_REPORT_BYTES));
    } catch (e) {
      return unusable(e);
    }
  }
  const mb = git(root, ["merge-base", baseRef, "HEAD"], { check: false }).trim();
  if (mb) {
    for (const commit of git(root, ["rev-list", `${mb}..HEAD`, "--", rel], { check: false }).split(/\s+/).filter(Boolean)) {
      for (const rev of [commit, `${commit}^`]) {
        if (hasFile(root, rev, rel)) {
          const [report, note] = parseLenient(showSmall(root, rev, rel, MAX_REPORT_BYTES));
          return [report, note ?? "Using the last committed report (the file was removed)."];
        }
      }
    }
  }
  return [null, null];
}

/** Blob ids introduced on the branch (reachable from target, not from the fork
 *  point). Content verified before a rebase isn't among them, and CI won't
 *  have it — so such files must be re-saved. */
function branchBlobs(root: string, target: string, mb: string): Set<string> {
  const out = git(root, ["rev-list", "--objects", target, "--not", mb], { check: false });
  return new Set(splitLines(out).filter(Boolean).map((l) => l.split(" ", 1)[0]));
}

function atomicWrite(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  const existingMode = (() => {
    try {
      return statSync(path).mode & 0o777;
    } catch {
      return null;
    }
  })();
  const tmp = join(dirname(path), `.${basename(path)}.${process.pid}.${Date.now()}.tmp`);
  try {
    writeFileSync(tmp, content, { encoding: "utf8", mode: 0o666, flag: "wx" }); // umask applies
    if (existingMode !== null) chmodSync(tmp, existingMode);
    renameSync(tmp, path);
  } catch (e) {
    try {
      unlinkSync(tmp);
    } catch {
      /* already gone */
    }
    throw e;
  }
}

