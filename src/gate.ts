/** The source text of the value at `path` in `raw` (valid JSON), or null if
 *  absent. A later duplicate key replaces an earlier one, as in JSON.parse.
 *  Lets the config tell `80.0` from `80`, which JSON.parse can't. */
function valueSource(raw: string, path: string[]): string | null {
  let i = 0;
  let found: string | null = null;
  const ws = () => {
    while (" \t\n\r".includes(raw[i]) && i < raw.length) i++;
  };
  const str = (): string => {
    const start = i++;
    while (raw[i] !== '"') i += raw[i] === "\\" ? 2 : 1;
    return JSON.parse(raw.slice(start, ++i)) as string;
  };
  // Skip one value without recursion, so deep nesting can't overflow the stack.
  const skip = () => {
    if (raw[i] === '"') return void str();
    if (raw[i] !== "{" && raw[i] !== "[") {
      while (i < raw.length && !",]} \t\n\r".includes(raw[i])) i++;
      return;
    }
    let depth = 0;
    do {
      if (raw[i] === '"') {
        str();
        continue;
      }
      if (raw[i] === "{" || raw[i] === "[") depth++;
      else if (raw[i] === "}" || raw[i] === "]") depth--;
      i++;
    } while (depth > 0);
  };
  const walk = (depth: number): void => {
    i++; // {
    ws();
    if (raw[i] === "}") return void i++;
    for (;;) {
      ws();
      const key = str();
      ws();
      i++; // :
      ws();
      if (key !== path[depth]) skip();
      else if (depth === path.length - 1) {
        const start = i;
        skip();
        found = raw.slice(start, i);
      } else {
        found = null;
        if (raw[i] === "{") walk(depth + 1);
        else skip();
      }
      ws();
      if (raw[i++] === "}") return;
    }
  };
  ws();
  if (raw[i] === "{") walk(0);
  return found;
}

function parseConfig(raw: string, where: string): Config {
  let data: unknown;
  try {
    data = JSON.parse(raw);
  } catch (e) {
    throw new GateError(`${where}: not valid JSON (${(e as Error).message}).`);
  }
  const section = isObj(data) ? (isObj(data.ownership_check) ? data.ownership_check : "ownership_check" in data ? data.ownership_check : data) : null;
  if (!isObj(section)) throw new GateError(`${where}: expected an object like {"ownership_check": {...}}.`);
  const cfg = { ...DEFAULT_CONFIG, ...section } as Record<string, unknown>;
  // Strict types: a string where a list belongs would be read character by
  // character, and "*" alone matches every path — silently disabling the gate.
  if (!["required", "suggested", "off"].includes(cfg.mode as string)) throw new GateError(`${where}: mode must be required, suggested or off.`);
  for (const key of ["sensitive", "ignore"]) {
    const v = cfg[key];
    if (!Array.isArray(v) || !v.every((x) => typeof x === "string" && x)) throw new GateError(`${where}: "${key}" must be a list of glob strings.`);
    for (const pat of v as string[]) {
      try {
        fnmatch("", pat);
      } catch {
        throw new GateError(`${where}: "${key}" has a pattern that can't be used: ${JSON.stringify(pat)}.`);
      }
    }
  }
  for (const key of ["base", "skip_label"]) {
    if (typeof cfg[key] !== "string") throw new GateError(`${where}: "${key}" must be a string.`);
  }
  for (const key of ["min_summary_chars", "small_change_lines", "small_summary_chars"]) {
    const m = cfg[key];
    const literal = valueSource(raw, section === data ? [key] : ["ownership_check", key]);
    const floatLiteral = literal !== null && /[.eE]/.test(literal);
    if (typeof m !== "number" || !Number.isInteger(m) || m < 0 || floatLiteral) throw new GateError(`${where}: "${key}" must be a non-negative integer.`);
  }
  return { ...(cfg as unknown as Config), _configured: true };
}

const MAX_CONFIG_BYTES = 256 * 1024;
const MAX_REPORT_BYTES = 4 * 1024 * 1024;

/** Read a repo-controlled file safely: never through a symlink (it could point
 *  at /dev/zero or a secret), never a FIFO, never more than `limit` bytes. */
function readSmall(path: string, limit: number): string {
  const st = lstat(path);
  if (!st || st.isSymbolicLink() || !st.isFile()) throw new GateError(`${basename(path)} must be a regular file, not a symlink or special file.`);
  const fd = openSync(path, "r");
  try {
    const buf = Buffer.alloc(limit + 1);
    let n = 0;
    for (;;) {
      const got = readSync(fd, buf, n, buf.length - n, null);
      if (got === 0) break;
      n += got;
      if (n > limit) throw new GateError(`${basename(path)} is larger than ${Math.floor(limit / 1024)} KB — refusing to read it.`);
    }
    return buf.subarray(0, n).toString("utf8");
  } finally {
    closeSync(fd);
  }
}

/** `git show rev:rel` with the same size bound (checked before reading). */
function showSmall(root: string, rev: string, rel: string, limit: number): string {
  const size = git(root, ["cat-file", "-s", `${rev}:${rel}`], { check: false }).trim();
  if (!/^\d+$/.test(size)) throw new GateError(`${rel} at ${rev} isn't readable.`);
  if (Number(size) > limit) throw new GateError(`${rel} at ${rev} is larger than ${Math.floor(limit / 1024)} KB — refusing to read it.`);
  return git(root, ["show", `${rev}:${rel}`]);
}

const suggestedDefaults = (): Config => ({ ...DEFAULT_CONFIG, mode: "suggested", _configured: false });

/** Config from a commit or from the working tree. With none, the gate is
 *  'suggested' (nobody opted this repo in). */
export function loadConfig(root: string, rev?: string | null): Config {
  if (rev) {
    if (!hasFile(root, rev, CONFIG_PATH)) return suggestedDefaults();
    return parseConfig(showSmall(root, rev, CONFIG_PATH, MAX_CONFIG_BYTES), `${CONFIG_PATH} at ${rev}`);
  }
  const path = join(root, CONFIG_PATH);
  if (!lstat(path)) return suggestedDefaults();
  return parseConfig(readSmall(path, MAX_CONFIG_BYTES), CONFIG_PATH);
}

/** CI and hooks judge a change by the rules on the *base* branch. If the base
 *  has no config, the strict defaults apply — never the PR's own config,
 *  which the PR could have written to switch itself off. */
function rulesForVerify(root: string, baseRef: string): Config {
  if (hasFile(root, baseRef, CONFIG_PATH)) return parseConfig(showSmall(root, baseRef, CONFIG_PATH, MAX_CONFIG_BYTES), `${CONFIG_PATH} on ${baseRef}`);
  return { ...DEFAULT_CONFIG, _configured: false };
}

/** status/save use the rules CI will apply (the base's), so what passes
 *  locally passes in CI. Before the base has a config, fall back to the
 *  working tree's config, or 'suggested'. */
function rulesForLocal(root: string, baseRef: string): Config {
  if (hasFile(root, baseRef, CONFIG_PATH)) return rulesForVerify(root, baseRef);
  return loadConfig(root);
}

/** Gate-control files (CODEOWNERS-protected) by path; the team's notes and
 *  reports only as plain, non-executable files — a symlink, executable or
 *  submodule at those paths is a normal change like any other. */
export function isPlumbing(path: string, mode = "100644"): boolean {
  if (GATE_FILES.includes(path)) return true;
  return PLUMBING_RE.test(path) && (mode === "100644" || mode === "000000");
}

/** Submodule bumps can pull in any amount of code, so they're always
 *  sensitive. A gitlink or symlink at 'vendor/payments' is matched as if it
 *  were the folder, so '**\/payments/**' covers it. */
export function isSensitive(path: string, mode: string, cfg: Pick<Config, "sensitive">): boolean {
  if (mode === "160000") return true;
  return matches(path, cfg.sensitive) || matches(path + "/_", cfg.sensitive);
}

/** Ignored files don't need questions — unless they're also sensitive. */
const noQuestions = (path: string, mode: string, cfg: Config) => matches(path, cfg.ignore) && !isSensitive(path, mode, cfg);

function resolveBase(root: string, cfg: Pick<Config, "base">, base?: string | null): string {
  if (base) {
    if (!refExists(root, base)) throw new GateError(`Base ref '${base}' not found. In CI, check out with fetch-depth: 0.`);
    return base;
  }
  const names = cfg.base ? [cfg.base] : [];
  const head = git(root, ["symbolic-ref", "--quiet", "refs/remotes/origin/HEAD"], { check: false }).trim();
  if (head) names.push(head.replace(/^refs\/remotes\/origin\//, ""));
  names.push("main", "master");
  const candidates: string[] = [];
  for (const b of names) {
    if (b.includes("/") && ["origin", "upstream"].includes(b.split("/", 1)[0])) candidates.push(b);
    // In a fork, "upstream" is the real project; prefer it over the fork's own copy.
    else candidates.push(`upstream/${b}`, `origin/${b}`, b);
  }
  for (const ref of candidates) if (refExists(root, ref)) return ref;
  throw new GateError('Could not find the base branch. Set "base" in .learning/config.json or pass --base.');
}

function currentBranch(root: string, branch?: string | null): string {
  if (branch) return branch;
  if (process.env.GITHUB_HEAD_REF) return process.env.GITHUB_HEAD_REF;
  const name = git(root, ["symbolic-ref", "--quiet", "--short", "HEAD"], { check: false }).trim();
  if (!name) throw new GateError("Detached HEAD: pass --branch <name>.");
  return name;
}

