const SAME = ["ok", "rebased"]; // states where the verified change is intact
type State = "new" | "ok" | "stale" | "rebased";

/** new: not in the report · ok: the verified change · stale: changed since ·
 *  rebased: the verified change on a newer base, but the verified content is
 *  no longer in the branch's history (e.g. after a rebase) — re-save, no questions. */
function states(root: string, changes: Changes, old: Report | null, target: string, mb: string): Record<string, State> {
  const oldFiles = old ? old.files : dict<unknown>();
  let reachable: Set<string> | null = null;
  const out: Record<string, State> = dict();
  for (const [p, c] of Object.entries(changes)) {
    if (!own(oldFiles, p)) {
      out[p] = "new";
      continue;
    }
    const kind = matchKind(root, get(oldFiles, p), c);
    if (kind === "exact") out[p] = "ok";
    else if (kind === "merged") {
      reachable ??= branchBlobs(root, target, mb);
      out[p] = reachable.has((get(oldFiles, p) as Change).blob) ? "ok" : "rebased";
    } else out[p] = "stale";
  }
  return out;
}

/** One rule, shared by status and save. A file needs questions if it is
 *  sensitive, or if a report exists and the file is new or changed since then
 *  — unless it was verified before and is unchanged. Ignored files never need
 *  questions unless they're also sensitive. Untracked files count like any
 *  other: exempting them would let new code into a report unverified. */
function needsVerification(changes: Changes, st: Record<string, State>, old: Report | null, cfg: Config): string[] {
  const oldVerified = old ? old.verified : dict<string[]>();
  const out: string[] = [];
  for (const [path, c] of Object.entries(changes)) {
    if (noQuestions(path, c.mode, cfg)) continue;
    if (SAME.includes(st[path]) && get(oldVerified, path)?.length) continue;
    if (isSensitive(path, c.mode, cfg) || (old !== null && !SAME.includes(st[path]))) out.push(path);
  }
  return out;
}

const VERSION_RE = /^\/\/ ownership-gate-version: (\d+)/m;
const FEATURES_RE = /^\/\/ ownership-gate-features: (.*)$/m;

/** Does the base branch's gate (the copy CI runs) list `feature` in its header? */
function baseGateHas(root: string, baseRef: string, feature: string): boolean {
  if (!hasFile(root, baseRef, GATE_REL)) return false;
  try {
    const head = showSmall(root, baseRef, GATE_REL, 8 * 1024 * 1024).slice(0, 4096);
    return (FEATURES_RE.exec(head)?.[1] ?? "").trim().split(/\s+/).includes(feature);
  } catch {
    return false;
  }
}

/** Added + removed lines in `paths` between the fork point and `rev` (the
 *  working tree, as `git add -A` would commit it, when rev is null); null if
 *  one of them is binary. The diff options are fixed, so local diff config
 *  (algorithm, textconv, external tools) can't change the count. */
function changedLines(root: string, mb: string, rev: string | null, paths: Set<string>): number | null {
  const args = ["diff", "--numstat", "-z", "--no-renames", "--no-ext-diff", "--no-textconv", "--diff-algorithm=myers", "--ignore-submodules=none"];
  const raw = rev ? gitBytes(root, [...args, mb, rev]) : withWorktreeIndex(root, (env) => gitBytes(root, [...args, "--cached", mb], { env }));
  let total = 0;
  for (const rec of splitNul(raw)) {
    const t1 = rec.indexOf(9);
    const t2 = t1 < 0 ? -1 : rec.indexOf(9, t1 + 1);
    if (t2 < 0 || !paths.has(decodePath(rec.subarray(t2 + 1)))) continue;
    const added = rec.subarray(0, t1).toString("latin1");
    const removed = rec.subarray(t1 + 1, t2).toString("latin1");
    if (added === "-" || removed === "-") return null;
    total += Number(added) + Number(removed);
  }
  return total;
}

interface Small {
  small: boolean;
  lines: number | null; // null: not counted (nothing to count, or something sensitive / binary)
  note: string | null;
}

/** The fast path: a change is small when its non-ignored files add and remove
 *  at most small_change_lines lines in total, and nothing in it is sensitive, a
 *  submodule or binary. It then needs a summary of small_summary_chars instead
 *  of min_summary_chars; everything else is checked as usual. It only applies
 *  when the base branch's gate knows it, so local and CI always agree. */
function smallChange(root: string, baseRef: string, mb: string, rev: string | null, changes: Changes, cfg: Config): Small {
  const no = (lines: number | null = null, note: string | null = null): Small => ({ small: false, lines, note });
  const entries = Object.entries(changes);
  if (!cfg.small_change_lines || !entries.length) return no();
  if (entries.some(([p, c]) => isSensitive(p, c.mode, cfg) || c.base_mode === "160000")) return no();
  const counted = new Set(entries.filter(([p]) => !matches(p, cfg.ignore)).map(([p]) => p));
  const lines = changedLines(root, mb, rev, counted);
  if (lines === null || lines > cfg.small_change_lines) return no(lines);
  if (!baseGateHas(root, baseRef, "small-change")) {
    return no(lines, `This would count as a small change (${lines} changed lines), but the base branch's gate predates the fast path, so CI would ask for the full check. Upgrade it with \`gate.mjs install --upgrade\` in its own PR.`);
  }
  return { small: true, lines, note: null };
}

export function status(repo?: string | null, base?: string | null, branch?: string | null) {
  const root = repoRoot(repo);
  const baseRef = resolveBase(root, loadConfig(root), base);
  const cfg = rulesForLocal(root, baseRef);
  const br = currentBranch(root, branch);
  const [changes, untracked, mb] = collectChanges(root, baseRef, null);
  const [report, note] = previousReport(root, br, baseRef);
  const st = states(root, changes, report, "HEAD", mb);
  const oldVerified = report ? report.verified : dict<string[]>();
  const files = Object.entries(changes).map(([p, c]) => ({
    path: p,
    state: st[p],
    sensitive: isSensitive(p, c.mode, cfg),
    ignored: matches(p, cfg.ignore),
    untracked: untracked.has(p),
    verified: Boolean(get(oldVerified, p)?.length) && SAME.includes(st[p]),
  }));
  const notes = note ? [note] : [];
  if (Object.values(st).includes("rebased")) {
    notes.push("Some verified files were rebased: save the report again (no new questions needed), or CI won't be able to match them.");
  }
  const localGate = join(root, GATE_REL);
  if (isFile(localGate) && !isSymlink(localGate)) {
    let head = "";
    try {
      head = readSmall(localGate, 8 * 1024 * 1024).slice(0, 4096);
    } catch {
      /* unreadable: no note */
    }
    const v = VERSION_RE.exec(head);
    if (v && Number(v[1]) !== GATE_VERSION) {
      notes.push(`This repo's ${GATE_REL} is v${v[1]} but the running gate is v${GATE_VERSION}. CI runs the base branch's copy, so update whichever is older (the plugin, or \`gate.mjs install --upgrade\` in a PR).`);
    }
  }
  if (exists(localGate) && hasFile(root, baseRef, GATE_REL)) {
    let head = "";
    try {
      head = showSmall(root, baseRef, GATE_REL, 8 * 1024 * 1024).slice(0, 4096);
    } catch {
      /* unreadable: no note */
    }
    const v = VERSION_RE.exec(head);
    if (v && Number(v[1]) !== GATE_VERSION) {
      notes.push(`The base branch runs gate v${v[1]} but this one is v${GATE_VERSION}: merge the base branch first, or CI will reject the report.`);
    }
  }
  const small = smallChange(root, baseRef, mb, null, changes, cfg);
  if (small.note) notes.push(small.note);
  return {
    mode: cfg.mode, configured: cfg._configured, base: baseRef, branch: br, report: reportRelpath(br),
    report_exists: report !== null, files, must_verify: needsVerification(changes, st, report, cfg),
    small_change: small.small, changed_lines: small.lines,
    min_summary_chars: small.small ? cfg.small_summary_chars : cfg.min_summary_chars, notes,
  };
}
type Status = ReturnType<typeof status>;

function formatStatus(s: Status): string {
  const mode = s.mode + (s.configured ? "" : ", no .learning/config.json");
  const lines = [`Ownership check — branch ${s.branch} vs ${s.base} (mode: ${mode})`];
  if (!s.files.length) return [lines[0], "No changes — nothing to check.", ...s.notes].join("\n");
  lines.push(`Report: ${s.report} (${s.report_exists ? "exists" : "not yet saved"})`);
  for (const f of s.files) {
    const tags = [f.state, ...(["sensitive", "ignored", "untracked", "verified"] as const).filter((t) => f[t]).map((t) => (t === "sensitive" ? "SENSITIVE" : t))];
    lines.push(`- ${f.path} [${tags.join(", ")}]`);
  }
  if (s.must_verify.length) lines.push("Must be verified before saving: " + s.must_verify.join(", "));
  if (s.small_change) {
    lines.push(`Small change (${s.changed_lines} changed lines): one question is enough, and the summary needs at least ${s.min_summary_chars} characters.`);
  }
  lines.push(...s.notes);
  return lines.join("\n");
}

export function save(payload: Record<string, unknown>, repo?: string | null, base?: string | null, branch?: string | null): string {
  const root = repoRoot(repo);
  const baseRef = resolveBase(root, loadConfig(root), base);
  const cfg = rulesForLocal(root, baseRef);
  const br = currentBranch(root, branch);
  const [changes, untracked, mb] = collectChanges(root, baseRef, null);
  if (!Object.keys(changes).length) throw new GateError(`No changes vs ${baseRef} — nothing to report.`);

  const summary = pyStrip(String(payload.summary ?? ""));
  const len = pyLen(summary);
  // Only count lines when it can matter: a long enough summary passes either way.
  const minChars = len < cfg.min_summary_chars && smallChange(root, baseRef, mb, null, changes, cfg).small ? cfg.small_summary_chars : cfg.min_summary_chars;
  if (len < minChars) {
    throw new GateError(`The summary must be the developer's own description of what changed, why, and what could break — at least ${minChars} characters.`);
  }
  const rawVerified = payload.verified ?? {};
  if (!isObj(rawVerified)) throw new GateError('"verified" must map file paths to lists of concepts.');
  const verified: Record<string, string[]> = dict();
  for (const [path, concepts0] of Object.entries(rawVerified)) {
    const concepts = typeof concepts0 === "string" ? [concepts0] : Array.isArray(concepts0) ? concepts0 : [];
    const items = concepts.map((c) => String(c).trim()).filter(Boolean);
    if (items.length) verified[String(path).trim().replace(/^\.\//, "")] = items;
  }
  const unknown = sorted(Object.keys(verified).filter((p) => !own(changes, p)));
  if (unknown.length) throw new GateError(`Not part of this change: ${unknown.join(", ")}. Changed files: ${Object.keys(changes).join(", ")}`);

  const [old] = previousReport(root, br, baseRef);
  const st = states(root, changes, old, "HEAD", mb);
  const missing = needsVerification(changes, st, old, cfg).filter((p) => !own(verified, p));
  if (missing.length) throw new GateError("Still needs verification (sensitive, or new/changed since the last report): " + missing.join(", "));
  if (old) {
    // keep earlier verification for files whose verified change is intact
    for (const [p, concepts] of Object.entries(old.verified)) {
      if (own(changes, p) && SAME.includes(st[p]) && !own(verified, p)) verified[p] = concepts;
    }
  }
  const askable = Object.entries(changes).filter(([p, c]) => !noQuestions(p, c.mode, cfg));
  if (askable.length && !Object.keys(verified).length) throw new GateError("No verified files — the check needs at least one area the developer explained.");

  const data = { version: GATE_VERSION, branch: br, base: baseRef, date: today(), summary, verified, files: changes };
  const rel = reportRelpath(br);
  atomicWrite(join(root, rel), renderReport(data));
  const extra = sorted([...untracked].filter((p) => own(changes, p)));
  const note = extra.length ? ` Untracked files included: ${extra.join(", ")} — commit them too, or they'll show as changed.` : "";
  return `Saved ${rel}: ${Object.keys(changes).length} files fingerprinted, ${Object.keys(verified).length} verified. Commit it together with the code.${note}`;
}

export function verify(repo?: string | null, base?: string | null, branch?: string | null, rev = "HEAD", labels: string[] = []): [boolean, string[], string] {
  const root = repoRoot(repo);
  const baseRef = resolveBase(root, loadConfig(root, rev), base);
  const cfg = rulesForVerify(root, baseRef);
  if (cfg.mode === "off") return [true, [], "off"];
  if (labels.includes(cfg.skip_label)) return [true, [`Skipped by the '${cfg.skip_label}' label.`], "skipped"];
  const br = currentBranch(root, branch);
  const [changes, , mb] = collectChanges(root, baseRef, rev);
  if (!Object.keys(changes).length) return [true, [], cfg.mode];
  const report = readReport(root, br, rev);
  if (report === null) {
    if (Object.entries(changes).every(([p, c]) => noQuestions(p, c.mode, cfg))) return [true, ["Only ignored files changed (e.g. lockfiles) — no report needed."], cfg.mode];
    return [false, [`No ownership report for branch '${br}' (${reportRelpath(br)}). ${CHECK_ME_HINT}`], cfg.mode];
  }
  const st = states(root, changes, report, rev, mb);
  const by = (s: State) => Object.keys(changes).filter((p) => st[p] === s);
  const problems: string[] = [];
  const unverifiedSensitive = Object.entries(changes).filter(([p, c]) => isSensitive(p, c.mode, cfg) && !get(report.verified, p)?.length).map(([p]) => p);
  if (by("new").length) problems.push("Changed after the check (not in the report): " + by("new").join(", "));
  if (by("stale").length) problems.push("Changed after the check (differs from what was verified): " + by("stale").join(", "));
  if (by("rebased").length) problems.push("Verified before a rebase — save the report again, no new questions needed: " + by("rebased").join(", "));
  if (unverifiedSensitive.length) problems.push("Sensitive files not explicitly verified: " + unverifiedSensitive.join(", "));
  const len = pyLen(pyStrip(report.summary));
  const shortOk = () => len >= cfg.small_summary_chars && smallChange(root, baseRef, mb, rev, changes, cfg).small;
  if (len < cfg.min_summary_chars && !shortOk()) problems.push("The developer's summary is missing or too short.");
  if (problems.length && !(by("rebased").length && problems.length === 1)) problems.push(CHECK_ME_HINT);
  return [problems.length === 0, problems, cfg.mode];
}

// ---------------------------------------------------------------- push detection

const WRAPPERS = new Set(["sudo", "doas", "env", "command", "builtin", "exec", "time", "nohup", "nice", "stdbuf"]);
const WRAPPER_ARG_OPTS = new Set(["-u", "-g", "-C", "-h", "-p", "-n", "-f", "-o", "-i", "-e"]);
const SHELLS = new Set(["bash", "sh", "zsh", "dash", "ksh"]);
const GIT_ARG_OPTS = new Set(["-C", "-c", "--git-dir", "--work-tree", "--namespace", "--exec-path", "--config-env"]);
const GH_ARG_OPTS = new Set(["-R", "--repo", "--hostname"]);
const PUNCT = "();<>|&";

/** A small POSIX-style tokenizer: quotes and escapes respected, runs of
 *  `();<>|&` as their own tokens, `#` at a word start begins a comment.
 *  Returns null on an unterminated quote. */
function tokenize(command: string): string[] | null {
  const tokens: string[] = [];
  let cur = "";
  let inWord = false;
  let i = 0;
  const flush = () => {
    if (inWord) tokens.push(cur);
    cur = "";
    inWord = false;
  };
  while (i < command.length) {
    const c = command[i];
    if (c === " " || c === "\t" || c === "\r" || c === "\n") {
      flush();
      i++;
    } else if (PUNCT.includes(c)) {
      flush();
      let j = i;
      while (j < command.length && PUNCT.includes(command[j])) j++;
      tokens.push(command.slice(i, j));
      i = j;
    } else if (c === "#" && !inWord) {
      while (i < command.length && command[i] !== "\n") i++;
    } else if (c === "'") {
      const end = command.indexOf("'", i + 1);
      if (end < 0) return null;
      cur += command.slice(i + 1, end);
      inWord = true;
      i = end + 1;
    } else if (c === '"') {
      i++;
      inWord = true;
      for (;;) {
        if (i >= command.length) return null;
        const d = command[i];
        if (d === '"') {
          i++;
          break;
        }
        if (d === "\\" && i + 1 < command.length && '\\"$`\n'.includes(command[i + 1])) {
          cur += command[i + 1];
          i += 2;
        } else {
          cur += d;
          i++;
        }
      }
    } else if (c === "\\") {
      if (i + 1 < command.length) cur += command[i + 1];
      inWord = true;
      i += 2;
    } else {
      cur += c;
      inWord = true;
      i++;
    }
  }
  flush();
  return tokens;
}

function segments(command: string): string[][] {
  command = command.replace(/\\\n/g, " ").replace(/\n/g, ";");
  const tokens = tokenize(command) ?? command.split(/\s+/).filter(Boolean);
  const segs: string[][] = [];
  let seg: string[] = [];
  for (const tok of tokens) {
    if (tok && [...tok].every((c) => ";&|()".includes(c))) {
      segs.push(seg);
      seg = [];
    } else seg.push(tok);
  }
  segs.push(seg);
  return segs.filter((s) => s.length);
}

const base = (t: string) => t.split("/").pop() ?? t;

/** True if a shell command runs `git push` or `gh pr create/merge`. Tokenises
 *  like a shell (quotes respected), so `git stash push` or
 *  `git commit -m "then git push"` don't count, while `git -C repo push`,
 *  `sudo git push`, `bash -c "git push"` and `(git push)` do. */
export function isPushCommand(command: string, depth = 0): boolean {
  if (depth > 3) return false;
  for (let tokens of segments(command)) {
    let i = 0;
    while (i < tokens.length) {
      const tok = tokens[i];
      if (["{", "}", "!"].includes(tok) || /^[A-Za-z_][A-Za-z0-9_]*=/.test(tok)) i++;
      else if (WRAPPERS.has(base(tok))) {
        i++;
        while (i < tokens.length && tokens[i].startsWith("-")) i += WRAPPER_ARG_OPTS.has(tokens[i]) ? 2 : 1;
      } else break;
    }
    tokens = tokens.slice(i);
    if (!tokens.length) continue;
    const prog = base(tokens[0]);
    if (SHELLS.has(prog)) {
      for (let j = 1; j < tokens.length - 1; j++) {
        const t = tokens[j];
        if (t.startsWith("-") && !t.startsWith("--") && t.slice(1).includes("c")) {
          if (isPushCommand(tokens[j + 1], depth + 1)) return true;
          break;
        }
      }
    } else if (prog === "git") {
      let j = 1;
      while (j < tokens.length && tokens[j].startsWith("-")) j += GIT_ARG_OPTS.has(tokens[j]) ? 2 : 1;
      if (j < tokens.length && tokens[j] === "push") return true;
    } else if (prog === "gh") {
      let j = 1;
      while (j < tokens.length && tokens[j].startsWith("-")) j += GH_ARG_OPTS.has(tokens[j]) ? 2 : 1;
      if (tokens[j] === "pr" && j + 1 < tokens.length && ["create", "merge"].includes(tokens[j + 1])) return true;
    }
  }
  return false;
}

