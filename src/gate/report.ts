// The ownership report: a markdown file for reviewers with a JSON data block for the gate,
// at .learning/checks/<branch>.md.

import { join } from "node:path";
import { get, isRecord, lstat, own } from "../util.js";
import { MAX_REPORT_BYTES, readRepoFile } from "./files.js";
import { currentBranch, git, readFileAtRev, revHasFile } from "./git.js";
import { CHECKS_DIR, GATE_VERSION, GateError, sorted } from "./shared.js";

const DATA_MARKER = "<!-- ownership-data: generated by the ownership gate; do not edit by hand -->";

export interface Report {
  version?: unknown;
  branch?: string;
  base?: string;
  date?: string;
  summary: string;
  verified: Record<string, string[]>;
  files: Record<string, unknown>;
  _outdated?: boolean;
}

/** JSON with sorted keys, so reports are stable and diff-friendly. */
function sortedKeysJson(value: unknown, indent?: number): string {
  const sortDeep = (v: unknown): unknown =>
    Array.isArray(v)
      ? v.map(sortDeep)
      : isRecord(v)
        ? Object.fromEntries(sorted(Object.keys(v)).map((k) => [k, sortDeep(v[k])]))
        : v;
  return JSON.stringify(sortDeep(value), null, indent);
}

/** Percent-encode everything but letters, digits and `-_.~`. Used for the
 *  report's file name, so it's reversible: feature/x and feature-x never collide. */
function percentEncode(s: string): string {
  return encodeURIComponent(s).replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);
}

export const reportPath = (branch: string) => `${CHECKS_DIR}/${percentEncode(branch)}.md`;

export function renderReport(data: Report & { branch: string; date: string; base: string; version: number }): string {
  const lines = [
    `# Ownership check — ${data.branch}`,
    `Date: ${data.date} · Base: ${data.base} · Gate v${data.version}`,
    "",
    "## Summary (in the developer's own words)",
    data.summary.trim(),
    "",
    "## Verified understanding",
  ];
  for (const path of sorted(Object.keys(data.verified)))
    lines.push(`- \`${path}\` — ${(get(data.verified, path) ?? []).join("; ")}`);
  const unverified = sorted(Object.keys(data.files).filter((p) => !own(data.verified, p)));
  if (unverified.length)
    lines.push(
      "",
      `Also in this change (reviewed, no specific questions): ${unverified.map((p) => `\`${p}\``).join(", ")}`,
    );
  lines.push("", DATA_MARKER, "```json", sortedKeysJson(data, 1), "```", "");
  return lines.join("\n");
}

function extractDataBlock(text: string): string | null {
  const after = text.split(DATA_MARKER).slice(1).join(DATA_MARKER);
  const m = /```json\n([\s\S]*?)\n```/.exec(after);
  return m ? m[1] : null;
}

export function parseReport(text: string): Report {
  if (!text.includes(DATA_MARKER))
    throw new GateError("Report is missing its data block — run the check again to regenerate it.");
  const block = extractDataBlock(text);
  if (block === null) throw new GateError("Report data block is malformed — run the check again to regenerate it.");
  let data: unknown;
  try {
    data = JSON.parse(block);
  } catch (e) {
    throw new GateError(`Report data is not valid JSON (${(e as Error).message}) — run the check again.`);
  }
  if (!(isRecord(data) && isRecord(data.files) && isRecord(data.verified) && typeof data.summary === "string")) {
    throw new GateError("Report data has the wrong shape — run the check again to regenerate it.");
  }
  for (const v of Object.values(data.verified as Record<string, unknown>)) {
    if (!Array.isArray(v) || !v.every((x) => typeof x === "string"))
      throw new GateError("Report data has the wrong shape — run the check again to regenerate it.");
  }
  if (data.version !== GATE_VERSION) {
    throw new GateError(
      `Report was made by gate v${String(data.version)}; this gate is v${GATE_VERSION}. If your branch is behind the base, merge it first; then run the check again.`,
    );
  }
  return data as unknown as Report;
}

export function readReport(root: string, branch: string, rev?: string | null): Report | null {
  const rel = reportPath(branch);
  if (rev) {
    if (!revHasFile(root, rev, rel)) return null;
    return parseReport(readFileAtRev(root, rev, rel, MAX_REPORT_BYTES));
  }
  const path = join(root, rel);
  return lstat(path) ? parseReport(readRepoFile(path, MAX_REPORT_BYTES)) : null;
}

const unusableReport = (e: unknown): [Report, string] => [
  { files: {}, verified: {}, summary: "", _outdated: true },
  `Existing report can't be used (${(e as Error).message}); its files need verifying again.`,
];

/** Parse a report for status/save. An outdated or broken one isn't a dead end
 *  — but it isn't a clean slate either: its files are treated as needing
 *  re-verification, so deleting or corrupting a report can't reset the rules. */
function parseReportLeniently(text: string): [Report, string | null] {
  try {
    return [parseReport(text), null];
  } catch (e) {
    let files: Record<string, unknown> = {};
    if (text.includes(DATA_MARKER)) {
      try {
        const data = JSON.parse(extractDataBlock(text) ?? "null");
        if (isRecord(data) && isRecord(data.files)) files = data.files;
      } catch {
        /* keep empty */
      }
    }
    // Old-format entries never match, so every file in it reads as changed.
    return [
      { files, verified: {}, summary: "", _outdated: true },
      `Existing report can't be used (${(e as Error).message}); its files need verifying again.`,
    ];
  }
}

/** The report to compare against: the working-tree one, or if it's gone, the
 *  last one committed on this branch (so deleting it doesn't help). */
export function previousReport(root: string, branch: string, baseRef: string): [Report | null, string | null] {
  const rel = reportPath(branch);
  const path = join(root, rel);
  if (lstat(path)) {
    try {
      return parseReportLeniently(readRepoFile(path, MAX_REPORT_BYTES));
    } catch (e) {
      return unusableReport(e);
    }
  }
  const mb = git(root, ["merge-base", baseRef, "HEAD"], { check: false }).trim();
  if (mb) {
    for (const commit of git(root, ["rev-list", `${mb}..HEAD`, "--", rel], { check: false })
      .split(/\s+/)
      .filter(Boolean)) {
      for (const rev of [commit, `${commit}^`]) {
        if (revHasFile(root, rev, rel)) {
          const [report, note] = parseReportLeniently(readFileAtRev(root, rev, rel, MAX_REPORT_BYTES));
          return [report, note ?? "Using the last committed report (the file was removed)."];
        }
      }
    }
  }
  return [null, null];
}

/** The report's path if the working tree holds a valid report for the current
 *  branch that HEAD doesn't have yet (none in HEAD, or a different one). */
export function uncommittedReport(root: string): string | null {
  try {
    const rel = reportPath(currentBranch(root));
    const saved = sortedKeysJson(parseReport(readRepoFile(join(root, rel), MAX_REPORT_BYTES)));
    if (!revHasFile(root, "HEAD", rel)) return rel;
    let committed: string | null = null;
    try {
      committed = sortedKeysJson(parseReport(readFileAtRev(root, "HEAD", rel, MAX_REPORT_BYTES)));
    } catch {
      /* HEAD's copy is broken or outdated: the saved one is what's pending */
    }
    // Compare the data, not the bytes: line-ending conversion can change the file text.
    return saved === committed ? null : rel;
  } catch {
    return null;
  }
}
