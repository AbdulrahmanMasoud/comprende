#!/usr/bin/env python3
"""Ownership gate for the explain-as-you-build skill.

Ties an "I understand this change" report to the exact change it covers, and
refuses pushes/merges when the report is missing or the change moved on.

One stdlib-only file on purpose: it is copied into each repo as
.learning/gate.py, and that copy runs in the git hook, the Claude Code hook,
the MCP server, and CI — with nothing to install.

Commands (run from inside the repo, or pass --repo):
  status         Which changed files are new / stale / ok vs. the report
  save           Write the report; JSON {"summary": str, "verified": {path: [concepts]}} on stdin
  verify         Check a commit (default HEAD) against its report — used by CI
  pre-push       Git pre-push hook entry point (reads refs from stdin)
  claude-hook    Claude Code PreToolUse hook entry point (reads JSON from stdin)
  session-start  Claude Code SessionStart hook (plugin): auto-installs the git hook
  install        Add gate.py, config, CI workflow, Claude hook and git hook to a repo
  install-hooks  Install only the local git pre-push hook (once per clone)
  protect        Create the GitHub ruleset that makes the check required (gh; dry run by default)

How a change is identified: for each file, the git blob id and mode of the
verified content, plus the blob id it was changed from. No diff text is
hashed, so user git config can't make local and CI disagree. If the base
moves on (merge or rebase), the report still holds when a 3-way merge proves
the only new differences came from the base; anything else is "stale".
"""
from __future__ import annotations

