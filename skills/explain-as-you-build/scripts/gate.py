def ruleset_body(approvals: int = 1, code_owners: bool = True) -> dict:
    """A repository ruleset for the default branch. Rulesets layer on top of
    existing branch protection (the strictest rule wins), so creating one never
    weakens or replaces what a repo already has."""
    return {
        "name": RULESET_NAME,
        "target": "branch",
        "enforcement": "active",
        "conditions": {"ref_name": {"include": ["~DEFAULT_BRANCH"], "exclude": []}},
        "rules": [
            {"type": "pull_request", "parameters": {
                "required_approving_review_count": approvals,
                "require_code_owner_review": code_owners,
                "dismiss_stale_reviews_on_push": False,
                "require_last_push_approval": False,
                "required_review_thread_resolution": False}},
            {"type": "required_status_checks", "parameters": {
                "strict_required_status_checks_policy": False,
                "required_status_checks": [{"context": CHECK_NAME}]}},
        ],
    }


def _gh(root: Path, *args: str, input: str | None = None) -> str:
    if not shutil.which("gh"):
        raise GateError("The GitHub CLI (gh) isn't installed. Install it and run `gh auth login`, "
                        "or set this up by hand: see the README's 'Protect the branch' section.")
    proc = subprocess.run(["gh", *args], cwd=root, input=input, capture_output=True, text=True)
    if proc.returncode != 0:
        err = (proc.stderr or proc.stdout).strip()
        if "Upgrade to GitHub Pro" in err or "upgrade" in err.lower() and "plan" in err.lower():
            raise GateError("Rulesets aren't available for private repos on GitHub's free plan. Use "
                            "Settings → Branches → branch protection instead (see README).")
        if "403" in err or "Must have admin rights" in err or "Resource not accessible" in err:
            raise GateError("GitHub refused: creating rules needs admin access to this repository.")
        raise GateError(f"gh {' '.join(args[:2])} failed: {err}")
    return proc.stdout


def protect(repo: str | None = None, apply: bool = False, approvals: int = 1,
            code_owners: bool = True) -> list[str]:
    """Create the GitHub ruleset that makes the gate binding: PRs required,
    the 'Ownership check' status required, code-owner review for gate files.
    Without apply it only shows what it would do."""
    root = repo_root(repo)
    if not 0 <= approvals <= 10:
        raise GateError("--approvals must be between 0 and 10.")
    nwo = _gh(root, "repo", "view", "--json", "nameWithOwner", "-q", ".nameWithOwner").strip()
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", nwo):
        raise GateError(f"Couldn't tell which GitHub repo this is (got {nwo!r}).")
    try:
        existing = json.loads(_gh(root, "api", f"repos/{nwo}/rulesets") or "[]")
    except json.JSONDecodeError:
        existing = []
    for r in existing if isinstance(existing, list) else []:
        if isinstance(r, dict) and r.get("name") == RULESET_NAME:
            return [f"Ruleset '{RULESET_NAME}' already exists on {nwo}: "
                    f"https://github.com/{nwo}/rules/{r.get('id')}"]
    body = ruleset_body(approvals, code_owners)
    plan = [f"Ruleset for {nwo} (default branch): require a pull request with {approvals} approval(s)"
            + (" incl. code owners" if code_owners else "") + f", and the '{CHECK_NAME}' status check.",
            "It adds to existing branch protection; it doesn't replace it."]
    if code_owners:
        plan.append("Note: a code owner can't approve their own PR. On a one-person repo, use --no-code-owners.")
    if not apply:
        return [*plan, "Dry run — nothing changed. Rerun with --apply (needs admin) to create it.",
                json.dumps(body, indent=2)]
    created = json.loads(_gh(root, "api", "-X", "POST", f"repos/{nwo}/rulesets", "--input", "-",
                             input=json.dumps(body)) or "{}")
    return [*plan, f"Created: https://github.com/{nwo}/rules/{created.get('id')}"]


def install_hooks(repo: str | None = None, auto: bool = False) -> list[str]:
    """Install (or re-pin) the pre-push hook for the repo's current gate.py.

    auto=True (the plugin's SessionStart) only ever writes to this repo's own
    .git/hooks — never to a custom core.hooksPath, which is often a folder
    shared by every repo on the machine."""
    root = repo_root(repo)
    gate_file = root / LEARNING / "gate.py"
    if gate_file.is_symlink() or not gate_file.is_file():
        return [f"SKIPPED pre-push hook: {LEARNING}/gate.py is missing or not a regular file."]
    pin = hashlib.sha256(gate_file.read_bytes()).hexdigest()
    hooks_dir = Path(git(root, "rev-parse", "--git-path", "hooks").strip())
    if not hooks_dir.is_absolute():
        hooks_dir = root / hooks_dir
    configured = git(root, "config", "--get", "core.hooksPath", check=False).strip()
    if configured:
        custom = Path(os.path.expanduser(configured))
        custom = (custom if custom.is_absolute() else root / custom).resolve()
        if auto:
            return [f"SKIPPED pre-push hook: core.hooksPath is set ({configured}), so it wasn't added "
                    "automatically. Run `python3 -I .learning/gate.py install-hooks` to add it there."]
        if root.resolve() not in (custom, *custom.parents):
            return [f"SKIPPED pre-push hook: core.hooksPath ({configured}) is outside this repo and may be "
                    "shared by other repos. Add this line to its pre-push hook yourself: "
                    'python3 -I "$(git rev-parse --show-toplevel)/.learning/gate.py" pre-push "$@" || exit 1']
        hooks_dir = custom
    hook = hooks_dir / "pre-push"
    if hook.is_symlink():
        return [f"SKIPPED pre-push hook: {hook} is a symlink."]
    if hook.exists():
        text = hook.read_text(encoding="utf-8", errors="replace")
        if "explain-as-you-build ownership gate" not in text:
            return [f"SKIPPED pre-push hook: {hook} already exists. Add this line to it: "
                    'python3 -I "$(git rev-parse --show-toplevel)/.learning/gate.py" pre-push "$@" || exit 1']
        if f"pinned-sha256: {pin}" in text:
            return [f"pre-push hook already installed ({hook})"]
        verb = "re-pinned"
    else:
        verb = "installed"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    hook.write_text(PRE_PUSH_HOOK.format(pin=pin), encoding="utf-8", newline="\n")
    hook.chmod(0o755)
    return [f"{verb} pre-push hook ({hook}) for gate.py sha256 {pin[:12]}"]


def _merge_claude_settings(path: Path) -> str:
    settings = {}
    if path.exists() or path.is_symlink():
        try:
            settings = json.loads(read_small(path, MAX_CONFIG_BYTES) or "{}")
        except GateError as e:
            return f"SKIPPED Claude hook: {e}"
        except json.JSONDecodeError:
            return f"SKIPPED Claude hook: {path} is not valid JSON; add the hook by hand (see README)."
        if not isinstance(settings, dict):
            return f"SKIPPED Claude hook: {path} is not a JSON object; add the hook by hand."
    groups = settings.setdefault("hooks", {}).setdefault("PreToolUse", [])
    for group in groups:
        for h in group.get("hooks", []):
            if "gate.py" in h.get("command", "") and "claude-hook" in h.get("command", ""):
                return f"Claude hook already present ({path})"
    groups.append({"matcher": "Bash", "hooks": [{"type": "command", "command": CLAUDE_HOOK_COMMAND, "timeout": 60}]})
    atomic_write(path, json.dumps(settings, indent=2, ensure_ascii=False) + "\n")
    return f"merged a Claude Code PreToolUse hook into {path} (other settings kept)"


def _codeowners(root: Path, owner: str | None) -> str:
    lines = [f"/{p} {owner or '@your-team-lead'}" for p in GATE_FILES]
    if not owner:
        return ("MANUAL STEP 2: add to .github/CODEOWNERS (or rerun install with --owner @handle) and turn on "
                "'Require review from Code Owners' — otherwise a PR could edit the workflow to skip the check:\n  "
                + "\n  ".join(lines))
    if not re.fullmatch(r"@[\w.-]+(/[\w.-]+)?|[^@\s]+@[^@\s]+", owner):
        raise GateError(f"--owner must be a GitHub @user, @org/team, or an email; got {owner!r}.")
    path = root / ".github" / "CODEOWNERS"
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    have = {l.split()[0] for l in existing.splitlines() if l.strip() and not l.lstrip().startswith("#")}
    new = [l for l in lines if l.split()[0] not in have]
    if new:
        prefix = "" if not existing or existing.endswith("\n") else "\n"
        atomic_write(path, existing + prefix + "# Ownership gate: changes to the gate need lead review\n"
                     + "\n".join(new) + "\n")
    return (f"CODEOWNERS: {len(new)} entries added for {owner}. MANUAL STEP 2: turn on "
            "'Require review from Code Owners' in branch protection.")


def install(repo: str | None = None, upgrade: bool = False, owner: str | None = None) -> list[str]:
    root = repo_root(repo)
    done = []
    me = Path(__file__).resolve()
    target = root / LEARNING / "gate.py"
    if target.exists() and target.resolve() == me:
        done.append(f"{LEARNING}/gate.py is this file")
    elif target.exists() and not upgrade:
        same = target.read_bytes() == me.read_bytes()
        done.append(f"{LEARNING}/gate.py " + ("up to date" if same else "exists (pass --upgrade to replace)"))
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(me, target)
        target.chmod(0o755)
        done.append(f"wrote {LEARNING}/gate.py")

    cfg_path = root / CONFIG_PATH
    if cfg_path.exists():
        done.append(f"{CONFIG_PATH} exists (kept)")
    else:
        cfg = {k: v for k, v in DEFAULT_CONFIG.items()}
        try:
            cfg["base"] = resolve_base(root, {"base": ""}, None).split("/", 1)[-1]
        except GateError:
            cfg["base"] = "main"
        atomic_write(cfg_path, json.dumps({"ownership_check": cfg}, indent=2) + "\n")
        done.append(f"wrote {CONFIG_PATH} (base: {cfg['base']}, mode: required)")

    wf = root / ".github" / "workflows" / "ownership-check.yml"
    if wf.exists():
        done.append(f"{wf.relative_to(root)} exists (kept)")
    else:
        atomic_write(wf, WORKFLOW)
        done.append(f"wrote {wf.relative_to(root)}")

    done.append(_merge_claude_settings(root / ".claude" / "settings.json"))
    done += install_hooks(str(root))
    done.append("NEXT, after this is merged: run `python .learning/gate.py protect` (dry run, then --apply) to "
                "require the 'Ownership check' status on the default branch — without it CI only warns.")
    done.append(_codeowners(root, owner))
    return done


def _md_safe(text: str) -> str:
    """Report text comes from the PR author: no HTML, images, links, table
    breaks or code spans in the reviewer's summary."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for ch in ("\\", "[", "]", "|", "`", "*", "_"):
        text = text.replace(ch, "\\" + ch)
    return text


def job_summary(root: Path, branch: str, rev: str, base: str | None, passed: bool,
                messages: list[str], mode: str) -> str:
    """Markdown for the GitHub Actions job summary: what a reviewer needs at a glance."""
    icon = "✅" if passed else ("❌" if mode == "required" else "⚠️")
    title = {"off": "Ownership check is off", "skipped": "Ownership check skipped by label"}.get(
        mode, "Ownership check passed" if passed else "Ownership check failed")
    out = [f"## {icon} {title}", ""]
    if messages:
        out += [f"- {_md_safe(m)}" for m in messages] + [""]
    try:
        report = read_report(root, branch, rev=rev)
    except GateError:
        report = None
    if report:
        try:
            base_ref = resolve_base(root, load_config(root, rev=rev), base)
            cfg = rules_for_verify(root, base_ref)
        except GateError:
            cfg = dict(DEFAULT_CONFIG)
        out += ["### The developer's summary", "",
                *[f"> {_md_safe(l)}" for l in report["summary"].strip().splitlines()], "",
                "### Verified understanding", "", "| File | Concepts the developer explained |", "|---|---|"]
        for path in sorted(report["verified"]):
            entry = report["files"].get(path, {})
            mode_ = entry.get("mode", "100644") if isinstance(entry, dict) else "100644"
            tag = " 🔒" if is_sensitive(path, mode_, cfg) else ""
            concepts = "; ".join(_md_safe(c) for c in report["verified"][path])
            out.append(f"| {_md_safe(path)}{tag} | {concepts} |")
        rest = sorted(set(report["files"]) - set(report["verified"]))
        if rest:
            out += ["", f"<details><summary>Also in this change, no specific questions ({len(rest)})</summary>", "",
                    *[f"- {_md_safe(p)}" for p in rest], "", "</details>"]
        out += ["", f"<sub>🔒 sensitive · report: `{report_relpath(branch)}` · gate v{GATE_VERSION}. "
                "The report shows what was verified, never scores or mistakes.</sub>"]
    text = "\n".join(out) + "\n"
    return text[:60_000]


def _write_job_summary(text: str) -> None:
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        with contextlib.suppress(OSError):
            with open(path, "a", encoding="utf-8") as f:
                f.write(text)


# ---------------------------------------------------------------- CLI

def _ci(kind: str, messages: list[str]) -> None:
    if os.environ.get("GITHUB_ACTIONS") == "true":
        for m in messages:
            print(f"::{kind} title=Ownership check::{m}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gate.py", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--repo", help="Path inside the repository (default: current directory)")
    for name in ("status", "save", "verify"):
        p = sub.add_parser(name, parents=[common])
        p.add_argument("--base", help="Base ref, e.g. origin/main (default: from config / auto)")
        p.add_argument("--branch", help="Branch name (default: current branch or $GITHUB_HEAD_REF)")
        if name == "status":
            p.add_argument("--json", action="store_true")
        if name == "save":
            p.add_argument("--input", help="JSON file (default: stdin)")
        if name == "verify":
            p.add_argument("--rev", default="HEAD")
            p.add_argument("--labels-json", default="", help="PR label names as a JSON list")
    sub.add_parser("pre-push", parents=[common]).add_argument("hook_args", nargs="*")
    sub.add_parser("claude-hook").add_argument("--from-plugin", action="store_true")
    sub.add_parser("session-start")
    p = sub.add_parser("install", parents=[common])
    p.add_argument("--upgrade", action="store_true", help="Replace an existing .learning/gate.py")
    p.add_argument("--owner", help="GitHub @user or @org/team to own the gate files in CODEOWNERS")
    sub.add_parser("install-hooks", parents=[common])
    p = sub.add_parser("protect", parents=[common],
                       help="Create the GitHub ruleset that makes the check required (dry run unless --apply)")
    p.add_argument("--apply", action="store_true")
    p.add_argument("--approvals", type=int, default=1)
    p.add_argument("--no-code-owners", action="store_true")
    sub.add_parser("version")
    args = parser.parse_args(argv)

    try:
        if args.cmd == "version":
            print(GATE_VERSION)
        elif args.cmd == "status":
            st = status(args.repo, args.base, args.branch)
            print(json.dumps(st, indent=2, ensure_ascii=False) if args.json else format_status(st))
        elif args.cmd == "save":
            raw = Path(args.input).read_text(encoding="utf-8") if args.input else sys.stdin.read()
            try:
                payload = json.loads(raw)
            except json.JSONDecodeError as e:
                raise GateError(f"Input is not valid JSON: {e}") from e
            if not isinstance(payload, dict):
                raise GateError('Input must be a JSON object with "summary" and "verified".')
            print(save(payload, args.repo, args.base, args.branch))
        elif args.cmd == "verify":
            labels = []
            if args.labels_json.strip():
                try:
                    labels = [str(x) for x in json.loads(args.labels_json)]
                except (json.JSONDecodeError, TypeError):
                    raise GateError("--labels-json must be a JSON list of label names.") from None
            passed, messages, mode = verify(args.repo, args.base, args.branch, args.rev, labels)
            if os.environ.get("GITHUB_STEP_SUMMARY"):
                with contextlib.suppress(Exception):
                    root = repo_root(args.repo)
                    _write_job_summary(job_summary(root, current_branch(root, args.branch), args.rev,
                                                   args.base, passed, messages, mode))
            if passed:
                if messages:
                    _ci("warning" if mode == "skipped" else "notice", messages)
                print(messages[0] if messages else
                      ("Ownership check is off." if mode == "off" else "Ownership check passed."))
                return 0
            _ci("error" if mode == "required" else "warning", messages)
            print("Ownership check failed:\n- " + "\n- ".join(messages), file=sys.stderr)
            return 1 if mode == "required" else 0
        elif args.cmd == "pre-push":
            return pre_push(sys.stdin.read(), args.repo)
        elif args.cmd == "claude-hook":
            return claude_hook(sys.stdin.read(), from_plugin=args.from_plugin)
        elif args.cmd == "session-start":
            print(json.dumps(session_start(sys.stdin.read()), ensure_ascii=False))
        elif args.cmd == "install":
            print("\n".join(install(args.repo, args.upgrade, args.owner)))
        elif args.cmd == "install-hooks":
            print("\n".join(install_hooks(args.repo)))
        elif args.cmd == "protect":
            print("\n".join(protect(args.repo, args.apply, args.approvals, not args.no_code_owners)))
    except (GateError, OSError) as e:
        print(f"ownership gate: {e}", file=sys.stderr)
        _ci("error", [str(e)])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
