SAME = ("ok", "rebased")   # states where the verified change is intact


def _states(root: Path, changes: dict, old: dict | None, target: str, mb: str) -> dict[str, str]:
    """new: not in the report · ok: the verified change · stale: changed since ·
    rebased: the verified change on a newer base, but the verified content is
    no longer in the branch's history (e.g. after a rebase) — re-save, no questions."""
    old_files = old["files"] if old else {}
    reachable: set[str] | None = None
    states = {}
    for p, c in changes.items():
        if p not in old_files:
            states[p] = "new"
            continue
        kind = match_kind(root, old_files[p], c)
        if kind == "exact":
            states[p] = "ok"
        elif kind == "merged":
            if reachable is None:
                reachable = branch_blobs(root, target, mb)
            states[p] = "ok" if old_files[p]["blob"] in reachable else "rebased"
        else:
            states[p] = "stale"
    return states


def needs_verification(changes: dict, states: dict, old: dict | None, cfg: dict) -> list[str]:
    """One rule, shared by status and save. A file needs questions if it is
    sensitive, or if a report exists and the file is new or changed since then
    — unless it was verified before and is unchanged. Ignored files never need
    questions unless they're also sensitive. Untracked files count like any
    other: they're part of what `git add -A` would commit, and exempting them
    would let new code into a report unverified. (Scratch files belong in .gitignore.)"""
    old_verified = old["verified"] if old else {}
    out = []
    for path, c in changes.items():
        if no_questions(path, c["mode"], cfg):
            continue
        if states[path] in SAME and old_verified.get(path):
            continue
        if is_sensitive(path, c["mode"], cfg) or (old is not None and states[path] not in SAME):
            out.append(path)
    return out


def status(repo: str | None = None, base: str | None = None, branch: str | None = None) -> dict:
    root = repo_root(repo)
    base_ref = resolve_base(root, load_config(root), base)
    cfg = rules_for_local(root, base_ref)
    br = current_branch(root, branch)
    changes, untracked, mb = collect_changes(root, base_ref, rev=None)
    report, note = previous_report(root, br, base_ref)
    states = _states(root, changes, report, "HEAD", mb)
    old_verified = report["verified"] if report else {}
    files = [{"path": p, "state": states[p], "sensitive": is_sensitive(p, c["mode"], cfg),
              "ignored": matches(p, cfg["ignore"]), "untracked": p in untracked,
              "verified": bool(old_verified.get(p)) and states[p] in SAME} for p, c in changes.items()]
    notes = [note] if note else []
    if any(states[p] == "rebased" for p in changes):
        notes.append("Some verified files were rebased: save the report again (no new questions needed), "
                     "or CI won't be able to match them.")
    local_gate = root / LEARNING / "gate.py"
    if local_gate.is_file():
        local_v = re.search(r"^GATE_VERSION = (\d+)", local_gate.read_text(encoding="utf-8", errors="replace"), re.M)
        if local_v and int(local_v.group(1)) != GATE_VERSION:
            notes.append(f"This repo's .learning/gate.py is v{local_v.group(1)} but the running gate is "
                         f"v{GATE_VERSION}. CI runs the base branch's copy, so update whichever is older "
                         "(the plugin, or `gate.py install --upgrade` in a PR).")
    if local_gate.exists() and has_file(root, base_ref, f"{LEARNING}/gate.py"):
        base_v = re.search(r"^GATE_VERSION = (\d+)", git(root, "show", f"{base_ref}:{LEARNING}/gate.py"), re.M)
        if base_v and int(base_v.group(1)) != GATE_VERSION:
            notes.append(f"The base branch runs gate v{base_v.group(1)} but this one is v{GATE_VERSION}: "
                         "merge the base branch first, or CI will reject the report.")
    return {"mode": cfg["mode"], "configured": cfg["_configured"], "base": base_ref, "branch": br,
            "report": report_relpath(br), "report_exists": report is not None, "files": files,
            "must_verify": needs_verification(changes, states, report, cfg), "notes": notes}


def format_status(st: dict) -> str:
    mode = st["mode"] + ("" if st["configured"] else ", no .learning/config.json")
    lines = [f"Ownership check — branch {st['branch']} vs {st['base']} (mode: {mode})"]
    if not st["files"]:
        return "\n".join([lines[0], "No changes — nothing to check.", *st["notes"]])
    lines.append(f"Report: {st['report']} ({'exists' if st['report_exists'] else 'not yet saved'})")
    for f in st["files"]:
        tags = [f["state"]] + [t.upper() if t == "sensitive" else t
                               for t in ("sensitive", "ignored", "untracked", "verified") if f[t]]
        lines.append(f"- {f['path']} [{', '.join(tags)}]")
    if st["must_verify"]:
        lines.append("Must be verified before saving: " + ", ".join(st["must_verify"]))
    lines += st["notes"]
    return "\n".join(lines)


def save(payload: dict, repo: str | None = None, base: str | None = None, branch: str | None = None) -> str:
    root = repo_root(repo)
    base_ref = resolve_base(root, load_config(root), base)
    cfg = rules_for_local(root, base_ref)
    br = current_branch(root, branch)
    changes, untracked, mb = collect_changes(root, base_ref, rev=None)
    if not changes:
        raise GateError(f"No changes vs {base_ref} — nothing to report.")

    summary = str(payload.get("summary", "")).strip()
    if len(summary) < cfg["min_summary_chars"]:
        raise GateError(f"The summary must be the developer's own description of what changed, why, "
                        f"and what could break — at least {cfg['min_summary_chars']} characters.")
    raw_verified = payload.get("verified") or {}
    if not isinstance(raw_verified, dict):
        raise GateError('"verified" must map file paths to lists of concepts.')
    verified: dict[str, list[str]] = {}
    for path, concepts in raw_verified.items():
        if isinstance(concepts, str):
            concepts = [concepts]
        items = [str(c).strip() for c in (concepts or []) if str(c).strip()]
        if items:
            verified[str(path).strip().removeprefix("./")] = items
    unknown = sorted(set(verified) - set(changes))
    if unknown:
        raise GateError(f"Not part of this change: {', '.join(unknown)}. Changed files: {', '.join(changes)}")

    old, _note = previous_report(root, br, base_ref)
    states = _states(root, changes, old, "HEAD", mb)
    missing = [p for p in needs_verification(changes, states, old, cfg) if p not in verified]
    if missing:
        raise GateError("Still needs verification (sensitive, or new/changed since the last report): "
                        + ", ".join(missing))
    if old:  # keep earlier verification for files whose verified change is intact
        for p, concepts in old["verified"].items():
            if p in changes and states[p] in SAME and p not in verified:
                verified[p] = concepts
    askable = [p for p, c in changes.items() if not no_questions(p, c["mode"], cfg)]
    if askable and not verified:
        raise GateError("No verified files — the check needs at least one area the developer explained.")

    data = {"version": GATE_VERSION, "branch": br, "base": base_ref, "date": _dt.date.today().isoformat(),
            "summary": summary, "verified": verified, "files": changes}
    rel = report_relpath(br)
    atomic_write(root / rel, render_report(data))
    note = (f" Untracked files included: {', '.join(sorted(untracked & set(changes)))} — commit them too, "
            "or they'll show as changed.") if untracked & set(changes) else ""
    return (f"Saved {rel}: {len(changes)} files fingerprinted, {len(verified)} verified. "
            f"Commit it together with the code.{note}")


def verify(repo: str | None = None, base: str | None = None, branch: str | None = None,
           rev: str = "HEAD", labels: list[str] | None = None) -> tuple[bool, list[str], str]:
    """Returns (passed, messages, mode). Judges a commit, never the working tree,
    by the rules on the base branch."""
    root = repo_root(repo)
    base_ref = resolve_base(root, load_config(root, rev=rev), base)
    cfg = rules_for_verify(root, base_ref)
    if cfg["mode"] == "off":
        return True, [], "off"
    if labels and cfg["skip_label"] in labels:
        return True, [f"Skipped by the '{cfg['skip_label']}' label."], "skipped"
    br = current_branch(root, branch)
    changes, _, mb = collect_changes(root, base_ref, rev=rev)
    if not changes:
        return True, [], cfg["mode"]
    report = read_report(root, br, rev=rev)
    if report is None:
        if all(no_questions(p, c["mode"], cfg) for p, c in changes.items()):
            return True, ["Only ignored files changed (e.g. lockfiles) — no report needed."], cfg["mode"]
        return False, [f"No ownership report for branch '{br}' ({report_relpath(br)}). {CHECK_ME_HINT}"], cfg["mode"]
    states = _states(root, changes, report, rev, mb)
    problems = []
    by_state = {s: [p for p in changes if states[p] == s] for s in ("new", "stale", "rebased")}
    unverified_sensitive = [p for p, c in changes.items()
                            if is_sensitive(p, c["mode"], cfg) and not report["verified"].get(p)]
    if by_state["new"]:
        problems.append("Changed after the check (not in the report): " + ", ".join(by_state["new"]))
    if by_state["stale"]:
        problems.append("Changed after the check (differs from what was verified): " + ", ".join(by_state["stale"]))
    if by_state["rebased"]:
        problems.append("Verified before a rebase — save the report again, no new questions needed: "
                        + ", ".join(by_state["rebased"]))
    if unverified_sensitive:
        problems.append("Sensitive files not explicitly verified: " + ", ".join(unverified_sensitive))
    if len(report["summary"].strip()) < cfg["min_summary_chars"]:
        problems.append("The developer's summary is missing or too short.")
    if problems and not (by_state["rebased"] and len(problems) == 1):
        problems.append(CHECK_ME_HINT)
    return not problems, problems, cfg["mode"]


