_WRAPPERS = {"sudo", "doas", "env", "command", "builtin", "exec", "time", "nohup", "nice", "stdbuf"}
_WRAPPER_ARG_OPTS = {"-u", "-g", "-C", "-h", "-p", "-n", "-f", "-o", "-i", "-e"}
_SHELLS = {"bash", "sh", "zsh", "dash", "ksh"}
_GIT_ARG_OPTS = {"-C", "-c", "--git-dir", "--work-tree", "--namespace", "--exec-path", "--config-env"}
_GH_ARG_OPTS = {"-R", "--repo", "--hostname"}


def _segments(command: str) -> list[list[str]]:
    command = command.replace("\\\n", " ").replace("\n", ";")
    try:
        lex = shlex.shlex(command, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        tokens = command.split()
    segments, seg = [], []
    for tok in tokens:
        if tok and all(c in ";&|()" for c in tok):
            segments.append(seg)
            seg = []
        else:
            seg.append(tok)
    segments.append(seg)
    return [s for s in segments if s]


def is_push_command(command: str, _depth: int = 0) -> bool:
    """True if a shell command runs `git push` or `gh pr create/merge`.

    Tokenises like a shell (quotes respected), so `git stash push` or
    `git commit -m "then git push"` don't count, while `git -C repo push`,
    `sudo git push`, `bash -c "git push"` and `(git push)` do.
    """
    if _depth > 3:
        return False
    for tokens in _segments(command):
        i = 0
        while i < len(tokens):
            tok = tokens[i]
            if tok in ("{", "}", "!") or re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", tok):
                i += 1
            elif os.path.basename(tok) in _WRAPPERS:
                i += 1
                while i < len(tokens) and tokens[i].startswith("-"):
                    i += 2 if tokens[i] in _WRAPPER_ARG_OPTS else 1
            else:
                break
        tokens = tokens[i:]
        if not tokens:
            continue
        prog = os.path.basename(tokens[0])
        if prog in _SHELLS:
            for j, t in enumerate(tokens[1:-1], start=1):
                if t.startswith("-") and not t.startswith("--") and "c" in t[1:]:
                    if is_push_command(tokens[j + 1], _depth + 1):
                        return True
                    break
        elif prog == "git":
            j = 1
            while j < len(tokens) and tokens[j].startswith("-"):
                j += 2 if tokens[j] in _GIT_ARG_OPTS else 1
            if j < len(tokens) and tokens[j] == "push":
                return True
        elif prog == "gh":
            j = 1
            while j < len(tokens) and tokens[j].startswith("-"):
                j += 2 if tokens[j] in _GH_ARG_OPTS else 1
            if tokens[j:j + 1] == ["pr"] and len(tokens) > j + 1 and tokens[j + 1] in ("create", "merge"):
                return True
    return False


def _project_has_gate_hook(root: Path) -> bool:
    path = root / ".claude" / "settings.json"
    try:
        settings = json.loads(read_small(path, MAX_CONFIG_BYTES))
        return any("gate.py" in h.get("command", "") and "claude-hook" in h.get("command", "")
                   for g in settings.get("hooks", {}).get("PreToolUse", []) for h in g.get("hooks", []))
    except Exception:
        return False


def claude_hook(stdin_text: str, from_plugin: bool = False) -> int:
    """PreToolUse hook for Claude Code. Exit 2 blocks the call and shows
    stderr to Claude. It checks the current branch; pushes of other branches
    are checked by the pre-push hook and CI. Outside a repo with the gate
    installed, or on an unexpected crash, it allows the call: this hook is a
    reminder; CI is the lock.

    from_plugin: called by the plugin's hook. It stays out of the way when the
    repo already registers the same hook, so the check never runs twice."""
    try:
        payload = json.loads(stdin_text or "{}")
        command = (payload.get("tool_input") or {}).get("command", "")
        if payload.get("tool_name", "Bash") != "Bash" or not is_push_command(command):
            return 0
        cwd = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
        root = repo_root(cwd)
        if not (root / CONFIG_PATH).exists():
            return 0
        if from_plugin and _project_has_gate_hook(root):
            return 0  # the repo's own hook already runs; don't check twice
        # The plugin never executes code from the repo it's looking at (a cloned
        # repo could ship any .learning/gate.py); it applies its own logic to
        # the repo's data. CI, running the base branch's gate, stays the lock.
    except Exception:
        return 0
    try:
        passed, problems, mode = verify(repo=str(root))
    except GateError as e:  # e.g. a broken report: a real problem worth stopping for
        passed, problems, mode = False, [str(e)], "required"
    except Exception:
        return 0
    if passed or mode != "required":
        return 0
    print("Blocked by the ownership gate:\n- " + "\n- ".join(problems), file=sys.stderr)
    return 2


def session_start(stdin_text: str) -> dict:
    """SessionStart hook (plugin). In a repo that uses the gate: install the
    local pre-push hook if this clone lacks it, and tell Claude the repo is
    gated so the ownership-check protocol is followed. Elsewhere: nothing.
    Never raises — a session must always start."""
    try:
        payload = json.loads(stdin_text or "{}")
        root = repo_root(payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
        if not (root / CONFIG_PATH).exists():
            return {}
        cfg = load_config(root)
        if cfg["mode"] == "off":
            return {}
        lines = [f"This repository uses the ownership gate (mode: {cfg['mode']}). For any code change, "
                 "follow the explain-as-you-build skill's ownership check (read references/ownership-check.md): "
                 "brief in-flight questions, a final check before commit/PR, and a saved report."]
        repo_gate = root / LEARNING / "gate.py"
        if os.environ.get("OWNERSHIP_GATE_NO_AUTO_HOOK") != "1" and repo_gate.is_file():
            # The installed hook runs the repo's gate.py on every push. Only set
            # that up automatically when it's byte-identical to this (trusted)
            # copy — never for code we haven't seen.
            if repo_gate.read_bytes() != Path(__file__).read_bytes():
                lines.append("This repo's .learning/gate.py differs from the plugin's copy, so the local "
                             "pre-push hook was NOT installed automatically. If the user trusts this repo, they "
                             "can run `python .learning/gate.py install-hooks`; mention this in one line.")
            else:
                result = install_hooks(str(root), auto=True)[0]
                if result.startswith(("installed", "re-pinned")):
                    lines.append("The local pre-push git hook was just installed in this clone; mention it to "
                                 "the user in one line (set OWNERSHIP_GATE_NO_AUTO_HOOK=1 to opt out).")
                elif result.startswith("SKIPPED"):
                    lines.append("The gate's pre-push hook wasn't added: " + result)
        return {"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": " ".join(lines)}}
    except Exception:
        return {}


def pre_push(stdin_text: str, repo: str | None = None) -> int:
    try:
        root = repo_root(repo)
        base_branch = resolve_base(root, load_config(root), None).split("/", 1)[-1]
    except GateError:
        return 0
    failed = False
    for line in stdin_text.splitlines():
        parts = line.split()
        if len(parts) != 4:
            continue
        _local_ref, local_sha, remote_ref, _remote_sha = parts
        # The *remote* branch name is what CI will see as the PR head, whatever
        # the local ref was (HEAD, a sha, or a different branch name).
        if local_sha == ZERO_SHA or not remote_ref.startswith("refs/heads/"):
            continue  # deletion or tag
        branch = remote_ref.removeprefix("refs/heads/")
        if branch == base_branch:
            continue  # reports are per feature branch; the base is guarded by PRs + branch protection
        try:
            passed, problems, mode = verify(repo=str(root), branch=branch, rev=local_sha)
        except GateError as e:
            passed, problems, mode = False, [str(e)], "required"
        except OSError as e:
            print(f"ownership gate: skipped ({e})", file=sys.stderr)
            continue
        if passed:
            continue
        label = "blocked" if mode == "required" else "warning"
        print(f"\nOwnership gate {label} for '{branch}':\n- " + "\n- ".join(problems), file=sys.stderr)
        failed = failed or mode == "required"
    if failed:
        print("\n(Bypassing with --no-verify only delays this: CI runs the same check.)\n", file=sys.stderr)
    return 1 if failed else 0


