from pathlib import Path

GATE_VERSION = 3
LEARNING = ".learning"
CHECKS_DIR = f"{LEARNING}/checks"
CONFIG_PATH = f"{LEARNING}/config.json"
DATA_MARKER = "<!-- ownership-data: generated by gate.py; do not edit by hand -->"
ZERO_SHA = "0" * 40
REGULAR_MODES = ("100644", "100755")

DEFAULT_CONFIG = {
    "mode": "required",            # required | suggested | off
    "base": "",                    # empty = auto-detect (upstream/, origin/HEAD, main, master)
    "sensitive": ["**/auth/**", "**/payments/**", "**/migrations/**", "**/security/**"],
    # "ignore" = no questions asked. Ignored files are still tracked: changing
    # them after a report makes it stale, like any other file.
    "ignore": ["**/package-lock.json", "**/yarn.lock", "**/pnpm-lock.yaml", "**/poetry.lock",
               "**/Cargo.lock", "**/go.sum"],
    "min_summary_chars": 80,
    "skip_label": "skip-ownership-check",
}

# Files that control the gate. They're excluded from "the change to
# understand" and protected by CODEOWNERS review instead.
GATE_FILES = [CONFIG_PATH, f"{LEARNING}/gate.py", ".github/workflows/ownership-check.yml",
              ".claude/settings.json", ".github/CODEOWNERS"]
# Exact shapes only (no subfolders, markdown only), so nothing executable can hide here.
_PLUMBING_RE = re.compile(
    r"^\.learning/(checks/[^/]+\.md|decisions/[^/]+\.md|map\.md|[^/]+\.local\.md)$")

CHECK_ME_HINT = 'Ask Claude to run the ownership check ("check me" / "اختبرني"), then commit the report.'


class GateError(Exception):
    """A problem the user (or Claude) can act on; the message says how."""


# ---------------------------------------------------------------- git helpers



def _git_env(extra: dict | None = None) -> dict:
    """Environment for every git call the gate makes. core.fsmonitor can name
    a command in the repo's own .git/config; it's forced off for all calls
    (via GIT_CONFIG_*, which outranks every config file)."""
    env = {**os.environ, "GIT_LITERAL_PATHSPECS": "1", "LC_ALL": "C", "GIT_OPTIONAL_LOCKS": "0"}
    env.pop("GIT_DIFF_OPTS", None)
    try:
        n = int(env.get("GIT_CONFIG_COUNT", "0"))
    except ValueError:
        n = 0
    env.update({"GIT_CONFIG_COUNT": str(n + 1), f"GIT_CONFIG_KEY_{n}": "core.fsmonitor",
                f"GIT_CONFIG_VALUE_{n}": "false"})
    env.update(extra or {})
    return env


def git_bytes(root: Path, *args: str, env: dict | None = None, check: bool = True,
              input: bytes | None = None) -> bytes:
    try:
        proc = subprocess.run(["git", *args], cwd=root,
                              input=input, capture_output=True, env=_git_env(env))
    except OSError as e:
        raise GateError(f"Could not run git: {e}") from e
    if check and proc.returncode != 0:
        msg = proc.stderr.decode("utf-8", "replace").strip()
        raise GateError(f"git {' '.join(args[:3])} failed: {msg}")
    return proc.stdout


def git(root: Path, *args: str, env: dict | None = None, check: bool = True) -> str:
    return git_bytes(root, *args, env=env, check=check).decode("utf-8", "replace")


def repo_root(path: str | os.PathLike | None) -> Path:
    start = Path(path or os.getcwd()).expanduser().resolve()
    if not start.exists():
        raise GateError(f"Path does not exist: {start}")
    if start.is_file():
        start = start.parent
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=start,
                         capture_output=True, text=True, env=_git_env())
    if out.returncode != 0 or not out.stdout.strip():
        raise GateError(f"Not inside a git working tree: {start}")
    return Path(out.stdout.strip())


def ref_exists(root: Path, ref: str) -> bool:
    return subprocess.run(["git", "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"],
                          cwd=root, capture_output=True, env=_git_env()).returncode == 0


def has_file(root: Path, rev: str, rel: str) -> bool:
    return subprocess.run(["git", "cat-file", "-e", f"{rev}:{rel}"], cwd=root,
                          capture_output=True, env=_git_env()).returncode == 0


def read_blob(root: Path, sha: str) -> bytes | None:
    proc = subprocess.run(["git", "cat-file", "blob", sha], cwd=root, capture_output=True, env=_git_env())
    return proc.stdout if proc.returncode == 0 else None


# ---------------------------------------------------------------- config

def _parse_config(raw: str, where: str) -> dict:
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as e:
        raise GateError(f"{where}: not valid JSON ({e}).") from e
    section = data.get("ownership_check", data) if isinstance(data, dict) else None
    if not isinstance(section, dict):
        raise GateError(f'{where}: expected an object like {{"ownership_check": {{...}}}}.')
    cfg = dict(DEFAULT_CONFIG)
    cfg.update(section)
    # Strict types: a string where a list belongs would be read character by
    # character, and "*" alone matches every path — silently disabling the gate.
    if cfg["mode"] not in ("required", "suggested", "off"):
        raise GateError(f"{where}: mode must be required, suggested or off.")
    for key in ("sensitive", "ignore"):
        if not isinstance(cfg[key], list) or not all(isinstance(x, str) and x for x in cfg[key]):
            raise GateError(f'{where}: "{key}" must be a list of glob strings.')
    for key in ("base", "skip_label"):
        if not isinstance(cfg[key], str):
            raise GateError(f'{where}: "{key}" must be a string.')
    m = cfg["min_summary_chars"]
    if isinstance(m, bool) or not isinstance(m, int) or m < 0:
        raise GateError(f'{where}: "min_summary_chars" must be a non-negative integer.')
    cfg["_configured"] = True
    return cfg


MAX_CONFIG_BYTES = 256 * 1024
MAX_REPORT_BYTES = 4 * 1024 * 1024


def read_small(path: Path, limit: int) -> str:
    """Read a repo-controlled file safely: never through a symlink (it could
    point at /dev/zero or a secret) and never more than `limit` bytes."""
    if path.is_symlink() or not path.is_file():
        raise GateError(f"{path.name} must be a regular file, not a symlink or special file.")
    with open(path, "rb") as f:
        data = f.read(limit + 1)
    if len(data) > limit:
        raise GateError(f"{path.name} is larger than {limit // 1024} KB — refusing to read it.")
    return data.decode("utf-8", "replace")


def show_small(root: Path, rev: str, rel: str, limit: int) -> str:
    """`git show rev:rel` with the same size bound (checked before reading)."""
    size = git(root, "cat-file", "-s", f"{rev}:{rel}", check=False).strip()
    if not size.isdigit():
        raise GateError(f"{rel} at {rev} isn't readable.")
    if int(size) > limit:
        raise GateError(f"{rel} at {rev} is larger than {limit // 1024} KB — refusing to read it.")
    return git(root, "show", f"{rev}:{rel}")


def load_config(root: Path, rev: str | None = None) -> dict:
    """Config from a commit or from the working tree. With none, the gate is
    'suggested' (nobody opted this repo in)."""
    if rev:
        if not has_file(root, rev, CONFIG_PATH):
            return {**DEFAULT_CONFIG, "mode": "suggested", "_configured": False}
        return _parse_config(show_small(root, rev, CONFIG_PATH, MAX_CONFIG_BYTES), f"{CONFIG_PATH} at {rev}")
    path = root / CONFIG_PATH
    if not (path.exists() or path.is_symlink()):
        return {**DEFAULT_CONFIG, "mode": "suggested", "_configured": False}
    return _parse_config(read_small(path, MAX_CONFIG_BYTES), CONFIG_PATH)


def rules_for_verify(root: Path, base_ref: str) -> dict:
    """CI and hooks judge a change by the rules on the *base* branch. If the
    base has no config, the strict defaults apply — never the PR's own config,
    which the PR could have written to switch itself off."""
    if has_file(root, base_ref, CONFIG_PATH):
        return _parse_config(show_small(root, base_ref, CONFIG_PATH, MAX_CONFIG_BYTES), f"{CONFIG_PATH} on {base_ref}")
    return {**DEFAULT_CONFIG, "_configured": False}


def rules_for_local(root: Path, base_ref: str) -> dict:
    """status/save use the same rules CI will apply (the base's), so what
    passes locally passes in CI. Before the base has a config, fall back to
    the working tree's config, or 'suggested'."""
    if has_file(root, base_ref, CONFIG_PATH):
        return rules_for_verify(root, base_ref)
    return load_config(root)


def matches(path: str, patterns: list[str]) -> bool:
    for pat in patterns:
        if fnmatch.fnmatchcase(path, pat):
            return True
        # Let "**/x/**" also match "x/..." at the repo root.
        if pat.startswith("**/") and fnmatch.fnmatchcase(path, pat[3:]):
            return True
    return False


def is_plumbing(path: str, mode: str = "100644") -> bool:
    """Gate-control files (CODEOWNERS-protected) by path; the team's notes and
    reports only as plain, non-executable files — a symlink, executable or
    submodule at those paths is a normal change like any other."""
    if path in GATE_FILES:
        return True
    return bool(_PLUMBING_RE.match(path)) and mode in ("100644", "000000")


def is_sensitive(path: str, mode: str, cfg: dict) -> bool:
    """Submodule bumps can pull in any amount of code, so they're always
    sensitive. A gitlink or symlink at 'vendor/payments' is matched as if it
    were the folder, so '**/payments/**' covers it."""
    if mode == "160000":
        return True
    return matches(path, cfg["sensitive"]) or matches(path + "/_", cfg["sensitive"])


def no_questions(path: str, mode: str, cfg: dict) -> bool:
    """Ignored files don't need questions — unless they're also sensitive."""
    return matches(path, cfg["ignore"]) and not is_sensitive(path, mode, cfg)


def resolve_base(root: Path, cfg: dict, base: str | None) -> str:
    if base:
        if not ref_exists(root, base):
            raise GateError(f"Base ref '{base}' not found. In CI, check out with fetch-depth: 0.")
        return base
    candidates = []
    names = [cfg["base"]] if cfg.get("base") else []
    head = git(root, "symbolic-ref", "--quiet", "refs/remotes/origin/HEAD", check=False).strip()
    if head:
        names.append(head.removeprefix("refs/remotes/origin/"))
    names += ["main", "master"]
    for b in names:
        if "/" in b and b.split("/", 1)[0] in ("origin", "upstream"):
            candidates.append(b)
        else:
            # In a fork, "upstream" is the real project; prefer it over the fork's own copy.
            candidates += [f"upstream/{b}", f"origin/{b}", b]
    for ref in candidates:
        if ref_exists(root, ref):
            return ref
    raise GateError("Could not find the base branch. Set \"base\" in .learning/config.json or pass --base.")


def current_branch(root: Path, branch: str | None) -> str:
    if branch:
        return branch
    if os.environ.get("GITHUB_HEAD_REF"):
        return os.environ["GITHUB_HEAD_REF"]
    name = git(root, "symbolic-ref", "--quiet", "--short", "HEAD", check=False).strip()
    if not name:
        raise GateError("Detached HEAD: pass --branch <name>.")
    return name


def report_relpath(branch: str) -> str:
    # Percent-encoding is reversible, so feature/x and feature-x never share a file.
    return f"{CHECKS_DIR}/{urllib.parse.quote(branch, safe='')}.md"


# ---------------------------------------------------------------- the change

_SAFE_BOOLS = {"", "true", "false", "yes", "no", "on", "off", "1", "0"}
# Applied to every git call that touches the working tree: fsmonitor can name
# a command, and hooks are never wanted on our throwaway index.
_WORKTREE_SAFE = ["-c", "core.fsmonitor=false", "-c", f"core.hooksPath={os.devnull}"]


def ensure_repo_config_is_inert(root: Path) -> None:
    """`git add` runs filter commands from git config. Filters the user set
    up globally (git-lfs, etc.) are theirs; filters defined in *this repo's*
    .git/config could come from someone else (a repo shared as an archive).
    Refuse those unless the user says they trust them."""
    if os.environ.get("OWNERSHIP_GATE_TRUST_REPO_CONFIG") == "1":
        return
    out = git(root, "config", "--show-scope", "--get-regexp", r"^filter\..*\.(clean|smudge|process)$",
              check=False)
    local = [line.split(None, 2)[1] for line in out.splitlines()
             if line.split(None, 1)[0] in ("local", "worktree") and len(line.split(None, 2)) > 1]
    if local:
        raise GateError("This repo's own .git/config defines filter commands (" + ", ".join(sorted(set(local)))
                        + ") that git would run while the gate reads your changes. If you set these up "
                        "yourself (e.g. git-crypt, or git-lfs installed with --local), rerun with "
                        "OWNERSHIP_GATE_TRUST_REPO_CONFIG=1.")


@contextlib.contextmanager
def worktree_index(root: Path):
    """A throwaway copy of the index with everything `git add -A` would stage.

    Its blob ids are exactly what a commit would contain — clean filters,
    line-ending rules, file↔directory swaps and submodules included — and the
    user's real index is never touched.
    """
    real = Path(git(root, "rev-parse", "--git-path", "index").strip())
    if not real.is_absolute():
        real = root / real
    fd, tmp = tempfile.mkstemp(prefix="ownership-gate-index-")
    os.close(fd)
    try:
        if real.exists():
            # copy2 keeps the index's mtime. Git's "racy clean" protection
            # compares file mtimes against it; a fresh mtime would make git
            # trust stale stat data and miss a same-size edit made in the
            # same second as the last index write.
            shutil.copy2(real, tmp)
        else:
            os.unlink(tmp)
        env = {"GIT_INDEX_FILE": tmp}
        ensure_repo_config_is_inert(root)
        git_bytes(root, *_WORKTREE_SAFE, "add", "-A", env=env)
        yield env
    finally:
        for p in (tmp, tmp + ".lock"):
            with contextlib.suppress(FileNotFoundError):
                os.unlink(p)


def _decode_path(raw: bytes) -> str:
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        raise GateError(f"File name {raw!r} is not valid UTF-8; the gate can't track it reliably. "
                        "Rename it.") from None


def collect_changes(root: Path, base: str, rev: str | None) -> tuple[dict[str, dict], set[str]]:
    """({path: {"mode", "blob", "base"}}, untracked paths) for every file the
    change touches against the fork point, gate plumbing excluded.

    rev=None means the working tree, as `git add -A` would commit it.
    Only `git diff --raw` is used: its output doesn't depend on diff.* config,
    attributes, or GIT_DIFF_OPTS.
    """
    target = rev or "HEAD"
    if not ref_exists(root, target):
        raise GateError("This branch has no commits yet — commit something first.")
    mb = git(root, "merge-base", base, target, check=False).strip()
    if not mb:
        raise GateError(f"No common history between {base} and {target}. "
                        "In CI, check out with fetch-depth: 0.")
    untracked: set[str] = set()
    with (contextlib.nullcontext(None) if rev else worktree_index(root)) as env:
        diff_args = [mb, rev] if rev else ["--cached", mb]
        raw = git_bytes(root, "diff", "--raw", "-z", "--no-abbrev", "--no-renames",
                        "--ignore-submodules=none", *diff_args, env=env)
        if not rev:
            out = git_bytes(root, *_WORKTREE_SAFE, "ls-files", "--others", "--exclude-standard", "-z")
            untracked = {_decode_path(p) for p in out.split(b"\0") if p}
    fields = raw.split(b"\0")
    changes: dict[str, dict] = {}
    i = 0
    while i < len(fields) - 1:
        meta = fields[i].decode("ascii", "replace")
        if not meta.startswith(":"):
            i += 1
            continue
        oldmode, newmode, oldsha, newsha, _status = meta[1:].split()[:5]
        path = _decode_path(fields[i + 1])
        i += 2
        if not is_plumbing(path, newmode):
            changes[path] = {"mode": newmode, "blob": newsha, "base": oldsha, "base_mode": oldmode}
    return dict(sorted(changes.items())), untracked, mb


def _merge3(root: Path, ours: bytes, base: bytes, theirs: bytes) -> bytes | None:
    with tempfile.TemporaryDirectory(prefix="ownership-gate-merge-") as d:
        paths = []
        for name, data in (("ours", ours), ("base", base), ("theirs", theirs)):
            p = os.path.join(d, name)
            with open(p, "wb") as f:
                f.write(data)
            paths.append(p)
        proc = subprocess.run(["git", "merge-file", "-p", "-q", *paths], cwd=d, capture_output=True,
                              env=_git_env())
        return proc.stdout if proc.returncode == 0 else None


def match_kind(root: Path, verified: dict, current: dict) -> str | None:
    """'exact' if `current` is the verified change; 'merged' if it is the
    verified change carried onto a newer base; None otherwise.

    For 'merged', the only accepted difference is the base's own edits: we
    replay them onto the verified content with a 3-way merge and require the
    result to equal the current content byte for byte. The file mode is
    merged the same way: the developer's mode change wins, else the base's.
    Anything else (a conflict, a binary file, a missing object) is a change.
    """
    if not isinstance(verified, dict) or not all(
            isinstance(verified.get(k), str) for k in ("mode", "blob", "base", "base_mode")):
        return None
    if verified == current:
        return "exact"
    expected_mode = current["base_mode"] if verified["mode"] == verified["base_mode"] else verified["mode"]
    if current["mode"] != expected_mode:
        return None
    if verified["base"] == current["base"]:
        # Base content unchanged: only a base mode change can explain a difference.
        return "merged" if current["blob"] == verified["blob"] else None
    if (current["mode"] not in REGULAR_MODES or verified["mode"] not in REGULAR_MODES
            or ZERO_SHA in (verified["blob"], verified["base"], current["base"], current["blob"])):
        return None
    blobs = [read_blob(root, s) for s in (verified["blob"], verified["base"], current["base"], current["blob"])]
    if any(b is None for b in blobs):
        return None
    v_blob, v_base, c_base, c_blob = blobs
    if any(b"\0" in b[:8000] for b in blobs):
        return None  # binary: no merging, must be re-verified
    return "merged" if _merge3(root, v_blob, v_base, c_base) == c_blob else None


def same_change(root: Path, verified: dict, current: dict) -> bool:
    return match_kind(root, verified, current) is not None


# ---------------------------------------------------------------- the report

def render_report(data: dict) -> str:
    lines = [
        f"# Ownership check — {data['branch']}",
        f"Date: {data['date']} · Base: {data['base']} · Gate v{data['version']}",
        "",
        "## Summary (in the developer's own words)",
        data["summary"].strip(),
        "",
        "## Verified understanding",
    ]
    for path in sorted(data["verified"]):
        lines.append(f"- `{path}` — " + "; ".join(data["verified"][path]))
    unverified = sorted(set(data["files"]) - set(data["verified"]))
    if unverified:
        lines += ["", "Also in this change (reviewed, no specific questions): "
                  + ", ".join(f"`{p}`" for p in unverified)]
    lines += ["", DATA_MARKER, "```json", json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True), "```", ""]
    return "\n".join(lines)


def parse_report(text: str) -> dict:
    if DATA_MARKER not in text:
        raise GateError("Report is missing its data block — run the check again to regenerate it.")
    m = re.search(r"```json\n(.*?)\n```", text.split(DATA_MARKER, 1)[1], re.S)
    if not m:
        raise GateError("Report data block is malformed — run the check again to regenerate it.")
    try:
        data = json.loads(m.group(1))
    except json.JSONDecodeError as e:
        raise GateError(f"Report data is not valid JSON ({e}) — run the check again.") from e
    if not (isinstance(data, dict) and isinstance(data.get("files"), dict)
            and isinstance(data.get("verified"), dict) and isinstance(data.get("summary"), str)):
        raise GateError("Report data has the wrong shape — run the check again to regenerate it.")
    if data.get("version") != GATE_VERSION:
        raise GateError(f"Report was made by gate v{data.get('version')}; this gate is v{GATE_VERSION}. "
                        "If your branch is behind the base, merge it first; then run the check again.")
    return data


def read_report(root: Path, branch: str, rev: str | None) -> dict | None:
    rel = report_relpath(branch)
    if rev:
        if not has_file(root, rev, rel):
            return None
        return parse_report(show_small(root, rev, rel, MAX_REPORT_BYTES))
    path = root / rel
    return parse_report(read_small(path, MAX_REPORT_BYTES)) if (path.exists() or path.is_symlink()) else None


def _parse_lenient(text: str) -> tuple[dict, str | None]:
    """Parse a report for status/save. An outdated or broken one isn't a dead
    end — but it isn't a clean slate either: its files are treated as needing
    re-verification, so deleting or corrupting a report can't reset the rules."""
    try:
        return parse_report(text), None
    except GateError as e:
        data = None
        if DATA_MARKER in text:
            m = re.search(r"```json\n(.*?)\n```", text.split(DATA_MARKER, 1)[1], re.S)
            with contextlib.suppress(Exception):
                data = json.loads(m.group(1)) if m else None
        files = data.get("files") if isinstance(data, dict) and isinstance(data.get("files"), dict) else {}
        # Old-format entries never match, so every file in it reads as changed.
        return ({"files": files, "verified": {}, "summary": "", "_outdated": True},
                f"Existing report can't be used ({e}); its files need verifying again.")


def previous_report(root: Path, branch: str, base_ref: str) -> tuple[dict | None, str | None]:
    """The report to compare against: the working-tree one, or if it's gone,
    the last one committed on this branch (so deleting it doesn't help)."""
    rel = report_relpath(branch)
    path = root / rel
    if path.exists() or path.is_symlink():
        try:
            return _parse_lenient(read_small(path, MAX_REPORT_BYTES))
        except GateError as e:
            return ({"files": {}, "verified": {}, "summary": "", "_outdated": True},
                    f"Existing report can't be used ({e}); its files need verifying again.")
    mb = git(root, "merge-base", base_ref, "HEAD", check=False).strip()
    if mb:
        for commit in git(root, "rev-list", f"{mb}..HEAD", "--", rel, check=False).split():
            for rev in (commit, f"{commit}^"):
                if has_file(root, rev, rel):
                    report, note = _parse_lenient(show_small(root, rev, rel, MAX_REPORT_BYTES))
                    return report, note or "Using the last committed report (the file was removed)."
    return None, None


def branch_blobs(root: Path, target: str, mb: str) -> set[str]:
    """Blob ids introduced on the branch (reachable from target, not from the
    fork point). Content verified before a rebase isn't among them, and CI
    won't have it — so such files must be re-saved."""
    out = git(root, "rev-list", "--objects", target, "--not", mb, check=False)
    return {line.split(" ", 1)[0] for line in out.splitlines() if line}


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        mode = path.stat().st_mode & 0o777
    else:
        umask = os.umask(0)
        os.umask(umask)
        mode = 0o666 & ~umask
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


